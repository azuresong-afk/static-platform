// 54.24: равновесие находим независимо (метод Ньютона по α)
const R24 = 0.5,
  P24 = 10,
  c24 = 200,
  l024 = 0.6;
let al24 = 0.3;
for (let i = 0; i < 60; i++) {
  const l = 2 * R24 * Math.sin(al24);
  const f = P24 * Math.tan(al24) - c24 * (l024 - l);
  const df = P24 / Math.cos(al24) ** 2 + c24 * 2 * R24 * Math.cos(al24);
  al24 -= f / df;
}
const l24 = 2 * R24 * Math.sin(al24);
const ka24 = Math.sqrt((G * Math.cos(al24)) / R24);
const ks24 = Math.sqrt(ka24 ** 2 + ((2 * G) / (P24 * R24 ** 2)) * (c24 * R24 ** 2 * Math.cos(al24) ** 2 + 0.5 * c24 * (l024 - l24) * R24 * Math.sin(al24)));

// 54.25: частоты без сопротивления — корни m₁m₂k⁴ − [(c₁ + c₂)m₂ + c₂m₁]k² + c₁c₂ = 0
