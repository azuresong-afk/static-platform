  D25 = Math.sqrt(B25 * B25 - 4 * m25[0] * m25[1] * c25[0] * c25[1]);
const k25 = [Math.sqrt((B25 - D25) / (2 * m25[0] * m25[1])), Math.sqrt((B25 + D25) / (2 * m25[0] * m25[1]))];

