import { newElem, type BeamScheme, type Elem, type Stage } from './model/elastic';
import type { OscProblem } from './model/osc';

type Over = {
  [K in keyof OscProblem]?: OscProblem[K] extends object ? (OscProblem[K] extends unknown[] ? OscProblem[K] : Partial<OscProblem[K]>) : OscProblem[K];
};

export const OSC_BASE: OscProblem = {
  len: 'cm',
  force: 'kG',
  gms: 9.81,
  byWeight: true,
  m: 1,
  orient: 'v',
  alpha: 30,
  Q: 0,
  el: { mode: 'c', c: 1, dst: 1, T0: 1, T0damped: false, stages: [{ items: [newElem('spring')] }], rope: false, mEl: 0, W: 0, sAllow: 0 },
  damp: { mode: 'none', b: 0, n: 0, q: 2, N: 1, T1: 1, f: 0.2, f0: 0 },
  exc: { mode: 'none', H: 1, m0: 0.1, e: 1, a: 1, p: 10, delta: 0 },
  init: { mode: 'eq', x0: 0, lambda0: 0, Fprev: 0, h: 0, v0: 0 },
  t: 0,
};

export const osc = (o: Over): OscProblem => {
  const b = structuredClone(OSC_BASE);
  return {
    ...b,
    ...o,
    el: { ...b.el, ...o.el },
    damp: { ...b.damp, ...o.damp },
    exc: { ...b.exc, ...o.exc },
    init: { ...b.init, ...o.init },
  } as OscProblem;
};

const sp = (c: number, o: Partial<Elem> = {}): Elem => ({ ...newElem('spring'), c, ...o });
const beam = (scheme: BeamScheme, E: number, J: number, l: number, a = 0): Elem => ({ ...newElem('beam'), scheme, E, J, l, a });
const rod = (E: number, A: number, l: number): Elem => ({ ...newElem('rod'), E, A, l });
const elems = (...stages: Elem[][]): Stage[] => stages.map((items) => ({ items }));

