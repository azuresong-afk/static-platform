/**
 * Пункт 28, «Удар и колебания»: колебательные системы, которые не сводятся к грузу на пружине (Мещерский §32, 39).
 *
 *  - rollers 32.10 — стержень на шкивах, вращающихся навстречу: ẍ + (fg/l)x = 0, T = 2π√(l/(fg));
 *  - arc     32.20–32.21 — груз на пружине скользит по дуге окружности с диаметром AB = l: k² = (g/l)(2 − (l − a)/b);
 *  - pretens 32.22 — пружина с предварительным натягом F₀ поперёк движения: k² = F₀/(m l);
 *  - stages  32.23 — сила Q прикладывается в крайнем нижнем положении: второй этап около нового положения равновесия;
 *  - three   32.49 — груз на пружине c₃, подвешенной к середине стержня на пружинах c₁, c₂;
 *  - energy  29.14, 32.50 — полная механическая энергия груза на пружине при разных началах отсчёта;
 *  - rolling 39.23 — тело с круглым основанием (полудиск, полушар) качается на плоскости без скольжения.
 */
import { ansB, bold, eqB, fail, parB, sample, sg, stepB, stepEx, type AskDef, type ExtraOut } from '../../../shared/extra';
import { OSC_ASKS2 } from './extra2';

const G = 9.81;
const D2R = Math.PI / 180;
const TAU = 2 * Math.PI;
const pos = (...x: number[]) => x.every((v) => v > 0 && Number.isFinite(v));
const done = (o: Omit<ExtraOut, 'ok' | 'errors'>): ExtraOut => ({ ok: true, errors: [], ...o });
const wave = (A: number, B: number, k: number, T: number) => sample((t) => A * Math.cos(k * t) + B * Math.sin(k * t), 0, 2 * T, 200);

