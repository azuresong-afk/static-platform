/**
 * Пункт 32: готовые задачи Мещерского §8 с ответами книги. Оси: x — к наблюдателю, y — вправо, z — вверх, если в
 * заметке не сказано иное. Ответ записан в правиле знаков приложения: реакции — силы, действующие на тело; у стержня
 * «+» — сжатие. Неизвестный момент пары задаётся парой сил с плечом 1 (две связанные силы): её модуль равен моменту.
 */
import type { Body, BodyForce, BodyPoint, BodySupport, V3 } from './model/body';
import type { BodyPreset } from './presets';

const rad = (a: number) => (a * Math.PI) / 180;
const S3 = Math.sqrt(3);

/** Точки строкой: «A 0 0 0; B 1 0 0». */
const pts = (s: string): BodyPoint[] =>
  s.split(';').map((t) => {
    const [name, x, y, z] = t.trim().split(/\s+/);
    return { name, x: +x, y: +y, z: +z };
  });

interface Spec {
  /** Точки строкой или списком. */
  p: string | BodyPoint[];
  /** Опоры: [вид, точка, ось | точка стержня | нормаль]. */
  s: [BodySupport['kind'], string, (string | V3)?][];
  /** Силы: точка, составляющие (или к точке to — модуль F), обозначение, неизвестна ли. */
  f: { at: string; c?: V3; to?: string; F?: number; name: string; unknown?: boolean; link?: string; k?: number }[];
  /** Неизвестный момент пары: обозначение, центр, направление момента. */
  m?: { name: string; at: V3; e: V3 }[];
  /** Известные пары. */
  pairs?: { M: V3; name?: string }[];
  faces?: string[][];
  edges?: [string, string][];
}

function perp(e: V3): [V3, V3] {
  const L = Math.hypot(...e);
  const u: V3 = [e[0] / L, e[1] / L, e[2] / L];
  const a: V3 = Math.abs(u[0]) < 0.9 ? [1, 0, 0] : [0, 1, 0];
  const p0: V3 = [
    a[0] - u[0] * (a[0] * u[0] + a[1] * u[1] + a[2] * u[2]),
    a[1] - u[1] * (a[0] * u[0] + a[1] * u[1] + a[2] * u[2]),
    a[2] - u[2] * (a[0] * u[0] + a[1] * u[1] + a[2] * u[2]),
  ];
  const lp = Math.hypot(...p0);
  const p: V3 = [p0[0] / lp, p0[1] / lp, p0[2] / lp];
  const q: V3 = [u[1] * p[2] - u[2] * p[1], u[2] * p[0] - u[0] * p[2], u[0] * p[1] - u[1] * p[0]];
  return [p, q];
}

function body(sp: Spec): Body {
  const points = typeof sp.p === 'string' ? pts(sp.p) : [...sp.p];
  const ix = (n: string) => {
    const i = points.findIndex((q) => q.name === n);
    if (i < 0) throw new Error('нет точки ' + n);
    return i;
  };
  const supports: BodySupport[] = sp.s.map(([kind, at, x]) => {
    if (kind === 'bearing') return { kind, at: ix(at), axis: (x as 'x' | 'y' | 'z') ?? 'z' };
    if (kind === 'rod') return { kind, at: ix(at), to: ix(x as string) };
    if (kind === 'normal') return { kind, at: ix(at), n: (x as V3) ?? [0, 0, 1] };
    return { kind, at: ix(at) };
  });
  const forces: BodyForce[] = sp.f.map((f) =>
    f.to != null
      ? { at: ix(f.at), mode: 'toward', F: f.F ?? 1, to: ix(f.to), name: f.name, unknown: f.unknown }
      : { at: ix(f.at), mode: 'comp', F: Math.hypot(...f.c!), c: f.c, name: f.name, unknown: f.unknown },
  );
  sp.f.forEach((f, j) => {
    if (f.link == null) return;
    forces[j].link = sp.f.findIndex((g) => g.name === f.link);
    forces[j].k = f.k ?? 1;
  });
  for (const m of sp.m ?? []) {
    // q×p… пара: в точке at + p/2 сила +q, в точке at − p/2 сила −q; момент равен F·(p×q) = F·e.
    const [p, q] = perp(m.e);
    const i = points.length;
    points.push({ name: m.name + '′', x: m.at[0] + p[0] / 2, y: m.at[1] + p[1] / 2, z: m.at[2] + p[2] / 2 });
    points.push({ name: m.name + '″', x: m.at[0] - p[0] / 2, y: m.at[1] - p[1] / 2, z: m.at[2] - p[2] / 2 });
    const lead = forces.length;
    forces.push({ at: i, mode: 'comp', F: 1, c: q, name: m.name, unknown: true });
    forces.push({ at: i + 1, mode: 'comp', F: 1, c: [-q[0], -q[1], -q[2]], name: m.name + '′', link: lead, k: 1 });
  }
  return {
    points,
    supports,
    forces,
    pairs: (sp.pairs ?? []).map((p) => ({ M: p.M, name: p.name })),
    edges: (sp.edges ?? []).map(([a, b]) => [ix(a), ix(b)] as [number, number]),
    faces: (sp.faces ?? []).map((f) => f.map(ix)),
  };
}

const s20 = Math.sin(rad(20)),
  c20 = Math.cos(rad(20)),
  s15 = Math.sin(rad(15)),
  c15 = Math.cos(rad(15));
/** 8.2: крыло k на радиусе 3 м — сила 100 кГ по нормали к крылу. */
const wing = (k: number) => {
  const a = rad(90 * k);
  return { at: 'W' + k, c: [-100 * s15 * Math.sin(a), 100 * s15 * Math.cos(a), 100 * c15] as V3, name: 'P' };
};
