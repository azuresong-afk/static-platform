/** Квадраты частот 2×2: det(K − ω²M) = 0. */
function freq2(M: number[][], K: number[][]): [number, number] {
  const a = M[0][0] * M[1][1] - M[0][1] * M[1][0];
  const b = -(K[0][0] * M[1][1] + K[1][1] * M[0][0] - K[0][1] * M[1][0] - K[1][0] * M[0][1]);
  const c = K[0][0] * K[1][1] - K[0][1] * K[1][0];
  const D = sqrt(b * b - 4 * a * c);
  return [sqrt((-b - D) / (2 * a)), sqrt((-b + D) / (2 * a))];
}

/** Интеграл Симпсона. */
function simpson(f: (x: number) => number, a: number, b: number, n = 400): number {
  const h = (b - a) / n;
  let s = f(a) + f(b);
  for (let i = 1; i < n; i++) s += f(a + i * h) * (i % 2 ? 4 : 2);
  return (s * h) / 3;
}
/** Функции Бесселя J₁ и Неймана Y₁ по интегральным представлениям. */
export const besselJ1 = (x: number) => simpson((t) => cos(t - x * sin(t)), 0, PI) / PI;
export const besselY1 = (x: number) =>
  simpson((t) => sin(x * sin(t) - t), 0, PI) / PI - simpson((t) => (exp(t) - exp(-t)) * exp(-x * Math.sinh(t)), 0, 12, 2400) / PI;

/** Рунге — Кутта для y' = f(t, y). */
function rk4(f: (t: number, y: number[]) => number[], y0: number[], tEnd: number, n = 4000): number[] {
  let y = y0.slice();
  const h = tEnd / n;
  for (let s = 0; s < n; s++) {
    const t = s * h;
    const k1 = f(t, y);
    const k2 = f(
      t + h / 2,
      y.map((v, i) => v + (h / 2) * k1[i]),
    );
    const k3 = f(
      t + h / 2,
      y.map((v, i) => v + (h / 2) * k2[i]),
    );
    const k4 = f(
      t + h,
      y.map((v, i) => v + h * k3[i]),
    );
    y = y.map((v, i) => v + (h / 6) * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]));
  }
  return y;
}

