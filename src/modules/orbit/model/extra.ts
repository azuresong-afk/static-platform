/**
 * Пункт 28, «Тяготение и орбиты»: выводы формул §50 на числах, стыковка, оптимальный радиус старта, метеориты (§28, 50).
 *
 *  - laws    50.7, 50.8, 50.14, 50.19, 50.26 — интеграл энергии v² − 2μ/r = h, коническое сечение r = p/(1 + e cos(φ − ε)),
 *              h = −μ/a (эллипс), 0 (парабола), μ/a (гипербола), третий закон Кеплера T²/a³ = 4π²/μ, высота круговой
 *              орбиты с равными кинетической и потенциальной (от поверхности) энергиями H = R/2;
 *  - dock    50.29 — стыковка спутников на круговой и эллиптической орбитах в точке касания: апоцентр новой орбиты;
 *  - escape  50.40 — касательный импульс с круговой орбиты на гиперболу с заданной v∞: наименьший при r₀ = 2μ/v∞²;
 *  - meteor  28.10 — два близких метеорита на одном эллипсе: расстояние между ними в афелии по расстоянию в перигелии.
 */
import { ansB, bold, eqB, fail, sample, sg, stepB, stepEx, type AskDef, type ExtraOut } from '../../../shared/extra';

const D2R = Math.PI / 180;
const MU_E = 398600;
const R_E = 6371;
const pos = (...x: number[]) => x.every((v) => v > 0 && Number.isFinite(v));
const done = (o: Omit<ExtraOut, 'ok' | 'errors'>): ExtraOut => ({ ok: true, errors: [], ...o });

/* ---------- 50.7, 50.8, 50.14, 50.19, 50.26 ---------- */
const A_LAWS: AskDef = {
  id: 'laws',
  title: '50.7–50.26: интеграл энергии, коническое сечение, h через элементы, третий закон Кеплера',
  hint: 'Точка в поле тяготения F = mμ/r². Начальное состояние: расстояние r₀, скорость v₀ и угол θ между скоростью и местным горизонтом. Формулы §50 проверяются на этих числах.',
  n: { mu: MU_E, R: R_E, r0: 7000, v0: 8, theta: 10 },
  fields: [
    { k: 'mu', label: 'гравитационный параметр μ, км³/с²' },
    { k: 'R', label: 'радиус планеты R, км (для 50.8)' },
    { k: 'r0', label: 'расстояние r₀, км' },
    { k: 'v0', label: 'скорость v₀, км/с' },
    { k: 'theta', label: 'угол скорости с местным горизонтом θ, °', neg: true },
  ],
  solve: (q, ex) => {
    const { mu, R, r0, v0, theta } = q.n;
    if (!pos(mu, R, r0, v0) || !(Math.abs(theta) < 90)) return fail(['μ, R, r₀, v₀ > 0; |θ| < 90°.']);
    const th = theta * D2R;
    const h = v0 * v0 - (2 * mu) / r0;
    const c = r0 * v0 * Math.cos(th);
    const p = (c * c) / mu;
    const e = Math.sqrt(Math.max(0, 1 + (h * c * c) / (mu * mu)));
    const vr = v0 * Math.sin(th);
    const eps = Math.atan2((vr * c) / mu, p / r0 - 1) / D2R; // направление на перицентр: r₀ = p/(1 + e cos(φ₀ − ε)), φ₀ = 0
    const a = h !== 0 ? -mu / h : Infinity;
    const T = h < 0 ? 2 * Math.PI * Math.sqrt(a ** 3 / mu) : NaN;
    const kepler = h < 0 ? (T * T) / a ** 3 : NaN;
    const H = R / 2;
    const kind = e < 1 - 1e-12 ? 'эллипс' : e > 1 + 1e-12 ? 'гипербола' : 'парабола';
    const hEl = h < 0 ? -mu / a : h > 0 ? mu / Math.abs(a) : 0;
    const steps = [
      stepEx(
        ex,
        '50.7: интеграл энергии',
        'Теорема об изменении кинетической энергии: работа силы mμ/r² на перемещении из r₀ в r равна mμ(1/r − 1/r₀); значит v² − 2μ/r постоянно.',
        eqB('v² − 2μ/r = h', `h = ${sg(v0 * v0)} − ${sg((2 * mu) / r0)} = ${sg(h)} км²/с²`),
      ),
      stepEx(
        ex,
        '50.14: траектория',
        'Формула Бине для u = 1/r: u″ + u = μ/c²; решение u = μ/c² + A cos(φ − ε) — коническое сечение с фокусом в центре.',
        eqB(
          'r = p/(1 + e cos(φ − ε)),  p = c²/μ,  e = √(1 + h c²/μ²)',
          `c = r₀v₀ cos θ = ${sg(c)} км²/с,  p = ${sg(p)} км,  e = ${sg(e)} (${kind}),  ε = ${sg(eps)}°`,
        ),
      ),
      stepEx(
        ex,
        '50.19: h через элементы',
        'Для эллипса большая полуось a = p/(1 − e²), отсюда h = −μ/a; для гиперболы h = μ/a; для параболы h = 0.',
        eqB(h < 0 ? `a = −μ/h = ${sg(a)} км;  −μ/a = ${sg(hEl)} = h` : h > 0 ? `a = μ/h = ${sg(Math.abs(a))} км;  μ/a = ${sg(hEl)} = h` : 'h = 0 — парабола'),
      ),
      stepEx(
        ex,
        '50.26: третий закон Кеплера',
        'Удвоенная секторная скорость c постоянна: c·T = 2πab, b = a√(1 − e²), c² = μp = μa(1 − e²).',
        eqB(
          'T²/a³ = 4π²/μ — одинаково для всех орбит вокруг данного центра',
          h < 0 ? `T = ${sg(T)} с,  T²/a³ = ${sg(kepler)},  4π²/μ = ${sg((4 * Math.PI ** 2) / mu)}` : 'орбита незамкнута — периода нет',
        ),
      ),
      stepEx(
        ex,
        '50.8: круговая орбита, K = Π',
        'На круговой орбите радиуса r = R + H: K = mμ/(2r); Π от поверхности = mμ(1/R − 1/r). Равенство даёт r = 3R/2.',
        eqB('H = R/2', `H = ${sg(H)} км`),
      ),
      stepB(
        'Ответ',
        ansB(
          [[bold(`h = ${sg(h)} км²/с²`)], 'постоянная энергии'],
          [[bold(`p = ${sg(p)} км,  e = ${sg(e)}`)], `${kind}`],
          ...(h < 0 ? [[[bold(`T²/a³ = ${sg(kepler)}`)], '= 4π²/μ'] as [string[], string]] : []),
          [`H = R/2 = ${sg(H)} км`, 'круговая орбита с K = Π', 'aux'],
        ),
      ),
    ];
    return done({ vals: { h, c, p, e, a, T, kepler, K3: (4 * Math.PI ** 2) / mu, hEl, H, HR: H / R }, steps });
  },
};

/* ---------- 50.29 ---------- */
const A_DOCK: AskDef = {
  id: 'dock',
  title: '50.29: стыковка спутников на круговой и эллиптической орбитах — апоцентр новой орбиты',
  hint: 'Круговая орбита радиуса r₀ и эллиптическая с перицентром r₀ и апоцентром n·r₀ касаются в перицентре; спутники соединяются в точке касания (неупругий удар) и движутся вместе.',
  n: { mu: MU_E, r0: 7000, n: 8, m1: 1, m2: 1 },
  fields: [
    { k: 'mu', label: 'μ, км³/с²' },
    { k: 'r0', label: 'радиус круговой орбиты r₀, км' },
    { k: 'n', label: 'апоцентр эллипса n·r₀: n' },
    { k: 'm1', label: 'масса спутника на круговой орбите m₁' },
    { k: 'm2', label: 'масса спутника на эллипсе m₂' },
  ],
  solve: (q, ex) => {
    const { mu, r0, n, m1, m2 } = q.n;
    if (!pos(mu, r0, m1, m2) || !(n >= 1)) return fail(['μ, r₀, m₁, m₂ > 0; n ≥ 1.']);
    const vc = Math.sqrt(mu / r0);
    const vp = Math.sqrt(((2 * mu) / r0) * (n / (1 + n)));
    const v = (m1 * vc + m2 * vp) / (m1 + m2);
    const den = (2 * mu) / (r0 * v * v) - 1;
    if (!(den > 0)) return fail(['После стыковки скорость не меньше параболической — орбита незамкнута.']);
    const ra = r0 / den;
    const steps = [
      stepEx(
        ex,
        'Скорости в точке касания',
        'Круговая скорость √(μ/r₀); в перицентре эллипса с a = (1 + n)r₀/2 по интегралу энергии v_p² = 2μ/r₀ − μ/a.',
        eqB(`v_c = √(μ/r₀) = ${sg(vc)} км/с`, `v_p = √(2μ n/(r₀(1 + n))) = ${sg(vp)} км/с`),
      ),
      stepEx(
        ex,
        'Стыковка',
        'Скорости в точке касания параллельны; соединение — неупругий удар: сохраняется количество движения.',
        eqB(`v = (m₁v_c + m₂v_p)/(m₁ + m₂) = ${sg(v)} км/с`),
      ),
      stepEx(
        ex,
        'Новая орбита',
        'Точка стыковки — перицентр новой орбиты (скорость перпендикулярна радиусу и больше круговой). Апоцентр — из интеграла энергии и закона площадей.',
        eqB('r_a = r₀/(2μ/(r₀v²) − 1)', `r_a = ${sg(ra)} км = ${sg(ra / r0)}·r₀`),
      ),
      stepB('Ответ', ansB([[bold(`r_a = ${sg(ra / r0)}·r₀ = ${sg(ra)} км`)], 'апоцентр новой орбиты'])),
    ];
    return done({ vals: { ra, ratio: ra / r0, v }, steps });
  },
};

/* ---------- 50.40 ---------- */
const A_ESCAPE: AskDef = {
  id: 'escape',
  title: '50.40: радиус круговой орбиты, с которой выход на гиперболу с заданной v∞ требует наименьшего импульса',
  hint: 'Касательный импульс Δv = √(v∞² + 2μ/r₀) − √(μ/r₀) переводит корабль с круговой орбиты радиуса r₀ на гиперболу с заданной скоростью на бесконечности.',
  n: { mu: MU_E, vinf: 3, r0: 7000 },
  fields: [
    { k: 'mu', label: 'μ, км³/с²' },
    { k: 'vinf', label: 'скорость на бесконечности v∞, км/с' },
    { k: 'r0', label: 'радиус орбиты для сравнения r₀, км' },
  ],
  solve: (q, ex) => {
    const { mu, vinf, r0 } = q.n;
    if (!pos(mu, vinf, r0)) return fail(['Все числа — положительные.']);
    const dv = (r: number) => Math.sqrt(vinf * vinf + (2 * mu) / r) - Math.sqrt(mu / r);
    const ropt = (2 * mu) / (vinf * vinf);
    const dvmin = dv(ropt);
    const steps = [
      stepEx(
        ex,
        'Импульс',
        'На гиперболе по интегралу энергии v² = v∞² + 2μ/r₀; на круговой орбите скорость √(μ/r₀); импульс касательный.',
        eqB('Δv(r₀) = √(v∞² + 2μ/r₀) − √(μ/r₀)', `при r₀ = ${sg(r0)} км: Δv = ${sg(dv(r0))} км/с`),
      ),
      stepEx(
        ex,
        'Минимум',
        'Обозначим x = μ/r₀: Δv = √(v∞² + 2x) − √x; dΔv/dx = 1/√(v∞² + 2x) − 1/(2√x) = 0 ⇒ 4x = v∞² + 2x ⇒ x = v∞²/2.',
        eqB('r₀ = 2μ/v∞²,  Δv_min = v∞/√2', `r₀ = ${sg(ropt)} км,  Δv_min = ${sg(dvmin)} км/с`),
      ),
      stepB(
        'Ответ',
        ansB(
          [[bold(`r₀ = 2μ/v∞² = ${sg(ropt)} км`)], 'радиус круговой орбиты с наименьшим импульсом'],
          [`Δv_min = ${sg(dvmin)} км/с`, 'наименьший импульс', 'aux'],
        ),
      ),
    ];
    return done({
      vals: { r0: ropt, dvmin },
      steps,
      plot: {
        xl: 'r₀, км',
        yl: 'Δv, км/с',
        series: [{ name: 'Δv(r₀)', pts: sample(dv, ropt / 5, ropt * 5, 150) }],
        marks: [{ x: ropt, y: dvmin, label: 'min' }],
      },
    });
  },
};

/* ---------- 28.10 ---------- */
const A_METEOR: AskDef = {
  id: 'meteor',
  title: '28.10: расстояние между двумя метеоритами на одном эллипсе в афелии',
  hint: 'Метеориты движутся друг за другом по одному эллипсу с равными секторными скоростями; дугу между ними считаем отрезком. В перигелии P (SP = R₁) расстояние a; найти расстояние в афелии A (SA = R₂).',
  n: { R1: 1, R2: 3, a: 1 },
  fields: [
    { k: 'R1', label: 'расстояние перигелия SP = R₁' },
    { k: 'R2', label: 'расстояние афелия SA = R₂' },
    { k: 'a', label: 'расстояние между метеоритами в перигелии a' },
  ],
  solve: (q, ex) => {
    const { R1, R2, a } = q.n;
    if (!pos(R1, R2, a) || !(R2 >= R1)) return fail(['R₁, R₂, a > 0, R₂ ≥ R₁.']);
    const d = (a * R1) / R2;
    const steps = [
      stepEx(ex, 'Закон площадей', 'В апсидах скорость перпендикулярна радиусу: v_P·R₁ = v_A·R₂ = c.', eqB('v_A/v_P = R₁/R₂')),
      stepEx(
        ex,
        'Расстояние между метеоритами',
        'Второй метеорит проходит каждую точку орбиты с одним и тем же запаздыванием Δt (равные секторные скорости, одна орбита): расстояние между ними ≈ v·Δt пропорционально скорости.',
        eqB('M₁M₂ (в афелии) = a·v_A/v_P = a·R₁/R₂', `= ${sg(d)}`),
      ),
      stepB('Ответ', ansB([[bold(`M₁M₂ = (R₁/R₂)·a = ${sg(d)}`)], 'расстояние между метеоритами в афелии'])),
    ];
    return done({ vals: { d }, steps });
  },
};

