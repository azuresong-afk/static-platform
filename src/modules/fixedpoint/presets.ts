type Tbl = number[][];
/** Таблица направляющих косинусов в ключи cIJ (строка — ось тела, столбец — неподвижная ось). */
const cKeys = (t: Tbl) => Object.fromEntries(t.flatMap((r, i) => r.map((v, j) => [`c${i}${j}`, v])));
const wKeys = (wF: number[], wB: number[]) => ({ wF0: wF[0], wF1: wF[1], wF2: wF[2], wB0: wB[0], wB1: wB[1], wB2: wB[2] });

/** 20.3–20.4: ψ = 0,5 + 0,4t, θ = 0,8 + 0,3t, φ = 1,2t − 0,2, t₁ = 1,5 с. */
function book2034() {
  const t = 1.5;
  const [ps, th, ph] = [0.5 + 0.4 * t, 0.8 + 0.3 * t, 1.2 * t - 0.2];
  const [dps, dth, dph] = [0.4, 0.3, 1.2];
  const [cp, sp, ct_, st, cf, sf] = [cos(ps), sin(ps), cos(th), sin(th), cos(ph), sin(ph)];
  return {
    ...cKeys([
      [cp * ct_ * cf - sp * sf, sp * ct_ * cf + cp * sf, -st * cf],
      [-cp * ct_ * sf - sp * cf, -sp * ct_ * sf + cp * cf, st * sf],
      [cp * st, sp * st, ct_],
    ]),
    ...wKeys([dph * st * cp - dth * sp, dph * st * sp + dth * cp, dph * ct_ + dps], [-dps * st * cf + dth * sf, dps * st * sf + dth * cf, dps * ct_ + dph]),
    w: sqrt(dps ** 2 + dth ** 2 + dph ** 2 + 2 * dps * dph * ct_),
  };
}
/** 20.5–20.6: самолётные углы ψ = 0,3t, θ = 0,2 + 0,1t, φ = 0,5t, t₁ = 2 с. */
function book2056() {
  const t = 2;
  const [ps, th, ph] = [0.3 * t, 0.2 + 0.1 * t, 0.5 * t];
  const [dps, dth, dph] = [0.3, 0.1, 0.5];
  const [cp, sp, ct_, st, cf, sf] = [cos(ps), sin(ps), cos(th), sin(th), cos(ph), sin(ph)];
  return {
    ...cKeys([
      [cp * ct_, st, -sp * ct_],
      [sp * sf - cp * st * cf, ct_ * cf, cp * sf + sp * st * cf],
      [sp * cf + cp * st * sf, -ct_ * sf, cp * cf - sp * st * sf],
    ]),
    ...wKeys([dph * cp * ct_ + dth * sp, dph * st + dps, -dph * sp * ct_ + dth * cp], [dps * st + dph, dps * ct_ * cf + dth * sf, -dps * ct_ * sf + dth * cf]),
  };
}
/** 20.7–20.8: корабельные углы ψ = 0,1 sin t, θ = 0,2 sin 0,5t, φ = 0,05t, t₁ = 1 с. */
function book2078() {
  const t = 1;
  const [ps, th, ph] = [0.1 * sin(t), 0.2 * sin(0.5 * t), 0.05 * t];
  const [dps, dth, dph] = [0.1 * cos(t), 0.1 * cos(0.5 * t), 0.05];
  const [cp, sp, ct_, st, cf, sf] = [cos(ps), sin(ps), cos(th), sin(th), cos(ph), sin(ph)];
  return {
    ...cKeys([
      [cp * cf + sp * st * sf, ct_ * sf, -sp * cf + cp * st * sf],
      [-cp * sf + sp * st * cf, ct_ * cf, sp * sf + cp * st * cf],
      [sp * ct_, -st, cp * ct_],
    ]),
    ...wKeys([dth * cp + dph * sp * ct_, dps - dph * st, -dth * sp + dph * cp * ct_], [dps * ct_ * sf + dth * cf, dps * ct_ * cf - dth * sf, -dps * st + dph]),
  };
}
/** 20.1: β = 0,4, α = 0,7; 20.2: α = 0,3, β = 0,6. */
function book201() {
  const [b, a] = [0.4, 0.7];
  return cKeys([
    [cos(b), 0, -sin(b)],
    [sin(a) * sin(b), cos(a), sin(a) * cos(b)],
    [cos(a) * sin(b), -sin(a), cos(a) * cos(b)],
  ]);
}
function book202() {
  const [a, b] = [0.3, 0.6];
  return cKeys([
    [cos(b), sin(a) * sin(b), -cos(a) * sin(b)],
    [0, cos(a), sin(a)],
    [sin(b), -sin(a) * cos(b), cos(a) * cos(b)],
  ]);
}

