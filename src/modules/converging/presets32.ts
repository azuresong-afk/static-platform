/** 6.7: натяжение струны BC из равновесия узла C (Q = 2 т, стрела AC из A = (0, 0, 0), B = (0, 0, 2)). */
const T67 = (() => {
  const bc = [-C67[0], 0, 2 - C67[2]],
    ca = [-C67[0], 0, -C67[2]];
  const lb = Math.hypot(...bc),
    la = Math.hypot(...ca);
  // x: T·bc₀/lb + S·ca₀/la = 0; z: −2 + T·bc₂/lb + S·ca₂/la = 0.
  const S = -(((bc[0] / lb) * 2) / ((bc[0] / lb) * (ca[2] / la) - (bc[2] / lb) * (ca[0] / la)));
  return Math.abs((S * (ca[0] / la)) / (bc[0] / lb));
})();
