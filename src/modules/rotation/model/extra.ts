/**
 * Пункт 28, «Вращение тела»: §37, 43, 44 Мещерского.
 *
 *  - magnet  37.25 — магнит в горизонтальном поле: J θ̈ = −A·H·θ, J = m(a² + b²)/3;
 *  - phys    37.37, 37.39 — физический маятник (ось может быть наклонена к вертикали на угол α) и точечная масса на
 *              прямой OC: T = 2π√((J_C + m a² + m₁d²)/((m a + m₁d) g sin α));
 *  - monkey  37.49–37.50 — человек лезет по канату, перекинутому через блок, с относительной скоростью u:
 *              кинетический момент относительно оси блока до и после — скорость груза;
 *  - couple  43.8, 44.21 — соединение дисков фрикционной муфтой и шкивов ремнём: сохранение кинетического момента
 *              (муфта) и импульсы натяжений ремня (ремень), потеря кинетической энергии.
 * Задания Яблонского Д.9 и Д.11 — в extraYab.ts.
 */
import { ROT_ASKS_YAB } from './extraYab';
import { ansB, bold, eqB, fail, parB, sample, sg, stepB, stepEx, type AskDef, type ExtraOut } from '../../../shared/extra';

const G = 9.81;
const D2R = Math.PI / 180;
const TAU = 2 * Math.PI;
const pos = (...x: number[]) => x.every((v) => v > 0 && Number.isFinite(v));
const done = (o: Omit<ExtraOut, 'ok' | 'errors'>): ExtraOut => ({ ok: true, errors: [], ...o });

/* ---------- 37.25 ---------- */
const A_MAGNET: AskDef = {
  id: 'magnet',
  title: '37.25: колебания магнита в магнитном поле Земли',
  hint: 'Призматический магнит массой m, длиной 2a и шириной 2b вращается вокруг вертикальной оси через центр тяжести; горизонтальная составляющая поля H, магнитный момент A (система CGS).',
  n: { m: 10, a: 5, b: 0.5, H: 0.2, A: 100 },
  fields: [
    { k: 'm', label: 'масса m, г' },
    { k: 'a', label: 'половина длины a, см' },
    { k: 'b', label: 'половина ширины b, см' },
    { k: 'H', label: 'горизонтальная составляющая поля H' },
    { k: 'A', label: 'магнитный момент A' },
  ],
  solve: (q, ex) => {
    const { m, a, b, H, A } = q.n;
    if (!pos(m, a, b, H, A)) return fail(['Все числа — положительные.']);
    const J = (m * (a * a + b * b)) / 3;
    const k = Math.sqrt((A * H) / J),
      T = TAU / k;
    const steps = [
      stepEx(
        ex,
        'Момент инерции',
        'Прямоугольная пластина (призма) со сторонами 2a и 2b относительно оси через центр, перпендикулярной этим сторонам: J = m[(2a)² + (2b)²]/12.',
        eqB(`J = m(a² + b²)/3 = ${sg(J)} г·см²`),
      ),
      stepEx(
        ex,
        'Уравнение вращения',
        'Полюсы ±μ на концах; пара сил μH с плечом 2a sin θ: момент −2aμH sin θ = −AH sin θ. При малых θ — гармонические колебания.',
        eqB('J θ̈ = −A H θ', `k = √(AH/J) = ${sg(k)} 1/с`),
      ),
      stepB('Ответ', ansB([[bold(`T = 2π√(m(a² + b²)/(3AH)) = ${sg(T)} с`)], 'период гармонических колебаний'])),
    ];
    return done({ vals: { T, J }, steps });
  },
};

/* ---------- 37.37, 37.39 ---------- */
const A_PHYS: AskDef = {
  id: 'phys',
  title: '37.37, 37.39: физический маятник (ось может быть наклонной), добавленная точечная масса',
  hint: 'Тело массой m, центр тяжести C на расстоянии a от оси подвеса O; ось образует угол α с вертикалью (α = 90° — горизонтальная ось). На прямой OC на расстоянии d от оси можно добавить точечную массу m₁.',
  n: { m: 1, l: 1, r: 1 / 6, Jc: 0.1, a: 0.5, alpha: 90, m1: 0.3, d: 85 / 72, g: G },
  s: { body: 'cyl' },
  selects: [
    {
      k: 'body',
      label: 'Тело',
      options: [
        ['cyl', 'круглый цилиндр длиной 2l, радиусом r; ось ⟂ оси цилиндра'],
        ['rod', 'тонкий стержень длиной 2l'],
        ['custom', 'задать момент инерции J_C'],
      ],
    },
  ],
  fields: [
    { k: 'm', label: 'масса тела m' },
    { k: 'l', label: 'половина длины l', show: (p) => p.s.body !== 'custom' },
    { k: 'r', label: 'радиус r', show: (p) => p.s.body === 'cyl' },
    { k: 'Jc', label: 'момент инерции J_C относительно оси через C', show: (p) => p.s.body === 'custom' },
    { k: 'a', label: 'расстояние OC = a' },
    { k: 'alpha', label: 'угол оси с вертикалью α, °' },
    { k: 'm1', label: 'точечная масса m₁ (0 — нет)', zero: true },
    { k: 'd', label: 'расстояние массы m₁ от оси d (по прямой OC)', neg: true },
    { k: 'g', label: 'g' },
  ],
  solve: (q, ex) => {
    const { m, l, r, a, alpha, m1, d, g } = q.n;
    if (!pos(m, a, g) || !(alpha > 0 && alpha <= 90) || !(m1 >= 0)) return fail(['m, a, g > 0; 0 < α ≤ 90°; m₁ ≥ 0.']);
    let Jc: number;
    if (q.s.body === 'cyl') {
      if (!pos(l, r)) return fail(['l, r > 0.']);
      Jc = m * ((r * r) / 4 + (l * l) / 3);
    } else if (q.s.body === 'rod') {
      if (!pos(l)) return fail(['l > 0.']);
      Jc = (m * l * l) / 3;
    } else {
      Jc = q.n.Jc;
      if (!(Jc >= 0)) return fail(['J_C ≥ 0.']);
    }
    const s = Math.sin(alpha * D2R);
    const J0 = Jc + m * a * a;
    const T0 = TAU * Math.sqrt(J0 / (m * a * g * s));
    const lr = J0 / (m * a);
    const J1 = J0 + m1 * d * d,
      M1 = m * a + m1 * d;
    if (!(M1 > 0)) return fail(['Центр тяжести системы оказался на оси или над ней: m·a + m₁·d ≤ 0.']);
    const T = TAU * Math.sqrt(J1 / (M1 * g * s));
    const steps = [
      stepEx(
        ex,
        'Момент инерции относительно оси подвеса',
        q.s.body === 'cyl'
          ? 'Цилиндр относительно оси через центр, перпендикулярной его оси: J_C = m(r²/4 + (2l)²/12); теорема Гюйгенса — Штейнера.'
          : q.s.body === 'rod'
            ? 'Стержень длиной 2l: J_C = m(2l)²/12.'
            : 'J_O = J_C + m a² (Гюйгенс — Штейнер).',
        eqB(`J_C = ${sg(Jc)},  J_O = J_C + m a² = ${sg(J0)}`),
      ),
      stepEx(
        ex,
        'Наклонная ось',
        'Ось подвеса наклонена к вертикали на угол α: восстанавливает только составляющая тяжести, перпендикулярная оси, mg sin α.',
        eqB('J_O φ̈ + m g a sin α · φ = 0', `T = 2π√(J_O/(m g a sin α)) = ${sg(T0)},  приведённая длина l_пр = J_O/(m a) = ${sg(lr)}`),
      ),
      ...(m1 > 0
        ? [
            stepEx(
              ex,
              'Добавленная масса',
              'Точечная масса m₁ меняет и момент инерции, и статический момент: J = J_O + m₁d², m·a + m₁·d. Если d равно приведённой длине (масса — в центре качаний), период не меняется.',
              eqB(`J = ${sg(J1)},  m a + m₁ d = ${sg(M1)}`, `T₁ = 2π√(J/((m a + m₁ d) g sin α)) = ${sg(T)}`),
            ),
            ...(Math.abs(d - lr) < 1e-9 * lr ? [stepB('Центр качаний', parB('d = J_O/(m a): масса добавлена в центре качаний — период прежний.'))] : []),
          ]
        : []),
      stepB(
        'Ответ',
        ansB(
          [[bold(`T = ${sg(m1 > 0 ? T : T0)}`)], m1 > 0 ? 'период с добавленной массой (с)' : 'период малых колебаний (с)'],
          ...(m1 > 0 ? [[`T₀ = ${sg(T0)}`, 'без добавленной массы', 'aux'] as [string, string, 'aux']] : []),
          [`l_пр = ${sg(lr)}`, 'приведённая длина', 'aux'],
        ),
      ),
    ];
    return done({ vals: { T0, T: m1 > 0 ? T : T0, lr }, steps });
  },
};

/* ---------- 37.49–37.50 ---------- */
const A_MONKEY: AskDef = {
  id: 'monkey',
  title: '37.49–37.50: человек поднимается по канату, перекинутому через блок',
  hint: 'За один конец каната держится человек массой m₁, к другому подвязан груз m₂. Человек начинает подниматься с постоянной скоростью u относительно каната. Блок: невесомый, масса на ободе или сплошной диск.',
  n: { m1: 1, m2: 1, M: 0.25, u: 1, t: 0, g: G },
  s: { block: 'rim' },
  selects: [
    {
      k: 'block',
      label: 'Блок',
      options: [
        ['none', 'невесомый'],
        ['rim', 'масса равномерно распределена по ободу'],
        ['disk', 'сплошной однородный диск'],
      ],
    },
  ],
  fields: [
    { k: 'm1', label: 'масса (вес) человека m₁' },
    { k: 'm2', label: 'масса (вес) груза m₂' },
    { k: 'M', label: 'масса (вес) блока M', show: (p) => p.s.block !== 'none' },
    { k: 'u', label: 'скорость человека относительно каната u' },
    { k: 't', label: 'момент времени t, с (при m₁ ≠ m₂)', zero: true },
    { k: 'g', label: 'g' },
  ],
  solve: (q, ex) => {
    const { m1, m2, u, t, g } = q.n;
    const M = q.s.block === 'none' ? 0 : q.n.M;
    if (!pos(m1, m2, u, g) || !(M >= 0) || !(t >= 0)) return fail(['m₁, m₂, u, g > 0; M, t ≥ 0.']);
    const Mr = q.s.block === 'rim' ? M : q.s.block === 'disk' ? M / 2 : 0; // J/R²
    const D = m1 + m2 + Mr;
    const v0 = (m1 * u) / D;
    const v = v0 + ((m1 - m2) * g * t) / D;
    const steps = [
      stepEx(
        ex,
        'Кинетический момент относительно оси блока',
        'Пусть канат движется так, что груз поднимается со скоростью v; тогда конец каната у человека опускается со скоростью v, а человек поднимается со скоростью u − v. Внутренние силы (человек тянет канат) момента относительно оси не дают.',
        eqB('K = m₂ v R − m₁ (u − v) R + J v/R', `J/R² = ${q.s.block === 'rim' ? 'M (обод)' : q.s.block === 'disk' ? 'M/2 (диск)' : '0'} = ${sg(Mr)}`),
      ),
      stepEx(
        ex,
        'Начало подъёма',
        'До начала движения K = 0. Сразу после рывка K тоже нуль (за ничтожно малое время момент сил тяжести импульса не даёт).',
        eqB('v₀ = m₁ u/(m₁ + m₂ + J/R²)', `v₀ = ${sg(v0)}`),
      ),
      ...(m1 !== m2
        ? [
            stepEx(
              ex,
              'Неравные веса',
              'Момент сил тяжести относительно оси (m₁ − m₂)gR меняет K: dK/dt = (m₁ − m₂) g R при u = const.',
              eqB('v = v₀ + (m₁ − m₂) g t/(m₁ + m₂ + J/R²)', `v(${sg(t)}) = ${sg(v)}`),
            ),
          ]
        : [stepB('Равные веса', parB('Моменты сил тяжести человека и груза уравновешены: K = 0 всё время, скорость груза постоянна.'))]),
      stepB(
        'Ответ',
        ansB(
          [[bold(`v = ${sg(v)}`)], `скорость подъёма груза (в единицах u: ${sg(v / u)}·u)`],
          [`u − v = ${sg(u - v)}`, 'абсолютная скорость человека', 'aux'],
        ),
      ),
    ];
    return done({
      vals: { v, ratio: v / u, vman: u - v },
      steps,
      plot:
        m1 !== m2 ? { xl: 't, с', yl: 'v', series: [{ name: 'v(t)', pts: sample((s) => v0 + ((m1 - m2) * g * s) / D, 0, Math.max(t, 1), 50) }] } : undefined,
    });
  },
};

/* ---------- 43.8, 44.21 ---------- */
const A_COUPLE: AskDef = {
  id: 'couple',
  title: '43.8, 44.21: соединение вращающихся дисков муфтой и шкивов ремнём',
  hint: 'Муфта: диски на одной оси, после соединения общая угловая скорость. Ремень (открытый, без скольжения): R₁ω₁ = R₂ω₂, импульсы натяжений ремня S·R₁ и S·R₂ меняют кинетические моменты шкивов.',
  n: { J1: 1, J2: 2, w1: 10, w2: 4, R1: 0.2, R2: 0.4 },
  s: { kind: 'clutch', J: 'radii' },
  selects: [
    {
      k: 'kind',
      label: 'Соединение',
      options: [
        ['clutch', 'фрикционная муфта (общая ось)'],
        ['belt', 'ремень между шкивами'],
      ],
    },
    {
      k: 'J',
      label: 'Моменты инерции шкивов',
      options: [
        ['radii', 'диски одинаковой плотности и толщины: J ∝ R⁴'],
        ['given', 'заданы J₁, J₂'],
      ],
      show: (p) => p.s.kind === 'belt',
    },
  ],
  fields: [
    { k: 'J1', label: 'момент инерции J₁', show: (p) => p.s.kind === 'clutch' || p.s.J === 'given' },
    { k: 'J2', label: 'момент инерции J₂', show: (p) => p.s.kind === 'clutch' || p.s.J === 'given' },
    { k: 'R1', label: 'радиус шкива R₁', show: (p) => p.s.kind === 'belt' },
    { k: 'R2', label: 'радиус шкива R₂', show: (p) => p.s.kind === 'belt' },
    { k: 'w1', label: 'угловая скорость ω₁₀', neg: true },
    { k: 'w2', label: 'угловая скорость ω₂₀', neg: true },
  ],
  solve: (q, ex) => {
    const { w1, w2 } = q.n;
    if (q.s.kind === 'clutch') {
      const { J1, J2 } = q.n;
      if (!pos(J1, J2)) return fail(['J₁, J₂ > 0.']);
      const w = (J1 * w1 + J2 * w2) / (J1 + J2);
      const dT = ((J1 * J2) / (2 * (J1 + J2))) * (w1 - w2) ** 2;
      const steps = [
        stepEx(
          ex,
          'Сохранение кинетического момента',
          'Силы трения муфты — внутренние для системы двух дисков: их моменты относительно общей оси взаимно уничтожаются.',
          eqB('J₁ω₁ + J₂ω₂ = (J₁ + J₂) ω', `ω = ${sg(w)}`),
        ),
        stepB('Потеря кинетической энергии', eqB('ΔT = J₁ω₁²/2 + J₂ω₂²/2 − (J₁ + J₂)ω²/2 = J₁J₂(ω₁ − ω₂)²/(2(J₁ + J₂))', `ΔT = ${sg(dT)}`)),
        stepB('Ответ', ansB([[bold(`ΔT = ${sg(dT)}`)], 'потеря кинетической энергии'], [`ω = ${sg(w)}`, 'общая угловая скорость', 'aux'])),
      ];
      return done({ vals: { w, dT }, steps });
    }
    const { R1, R2 } = q.n;
    if (!pos(R1, R2)) return fail(['R₁, R₂ > 0.']);
    const radii = q.s.J !== 'given';
    const J1 = radii ? R1 ** 4 : q.n.J1,
      J2 = radii ? R2 ** 4 : q.n.J2;
    if (!pos(J1, J2)) return fail(['J₁, J₂ > 0.']);
    // J₁(ω₁ − ω₁₀) = −S R₁, J₂(ω₂ − ω₂₀) = S R₂, ω₂ = R₁ω₁/R₂
    const W1 = (J1 * R2 * w1 + J2 * R1 * w2) / (J1 * R2 + (J2 * R1 * R1) / R2);
    const W2 = (R1 * W1) / R2;
    const dT = (J1 * (w1 * w1 - W1 * W1) + J2 * (w2 * w2 - W2 * W2)) / 2;
    const steps = [
      stepEx(
        ex,
        'Импульсы натяжений ремня',
        'Накинутый ремень за короткое время передаёт ударные импульсы натяжений; разность натяжений ветвей даёт импульс S: на первом шкиве момент −S R₁, на втором +S R₂. Скольжения нет — скорости точек ремня на шкивах равны.',
        eqB('J₁(ω₁ − ω₁₀) = −S R₁,  J₂(ω₂ − ω₂₀) = S R₂,  R₁ω₁ = R₂ω₂'),
      ),
      stepB(
        'Угловые скорости',
        eqB(
          ...(radii
            ? ['J ∝ R⁴ (одинаковые плотность и толщина): ω₁ = (R₁³ω₁₀ + R₂³ω₂₀)/(R₁(R₁² + R₂²)),  ω₂ = (R₁³ω₁₀ + R₂³ω₂₀)/(R₂(R₁² + R₂²))']
            : ['ω₁ = (J₁R₂ω₁₀ + J₂R₁ω₂₀)/(J₁R₂ + J₂R₁²/R₂)']),
          `ω₁ = ${sg(W1)},  ω₂ = ${sg(W2)}`,
        ),
      ),
      stepB(
        'Ответ',
        ansB(
          [[bold(`ω₁ = ${sg(W1)}`)], 'первый шкив'],
          [[bold(`ω₂ = ${sg(W2)}`)], 'второй шкив'],
          [radii ? `ΔT/(πρh/2) = ${sg(dT)}` : `ΔT = ${sg(dT)}`, 'потеря кинетической энергии', 'aux'],
        ),
      ),
    ];
    return done({ vals: { w1: W1, w2: W2, dT }, steps });
  },
};

