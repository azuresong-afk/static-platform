const DEF: SpState = { mode: 'compose', compose: compose({}), euler: euler({}), diff: diff({}), screw: screw({}), gyro: gyro({}) };
export const defaultState = (): SpState => structuredClone(DEF);
type Sub = { compose: ComposeProblem } | { euler: EulerProblem } | { diff: DiffProblem } | { screw: ScrewProblem } | { gyro: GyroProblem };
function st(s: Sub): SpState {
  const mode = Object.keys(s)[0] as SpMode;
  return { ...structuredClone(DEF), ...s, mode };
}

