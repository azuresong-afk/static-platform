/**
 * Решение задачи 6 Антонова: центр тяжести составного сечения, моменты инерции по теореме о параллельном
 * переносе, главные центральные оси, моменты сопротивления, нейтральный слой и напряжения при вертикальной нагрузке.
 */
import { sub, v, type Block, type Doc, type Inline, type Step } from '../../../shared/doc';
import { fmt } from '../../../shared/format';
import type { Part, SectionResult } from '../model/section';

const f = (x: number, d = 2) => fmt(x, d);
/** Число в скобках, если отрицательное: для записи «A·(−a)²». */
const fp = (x: number, d = 3) => (x < 0 ? `(${fmt(x, d)})` : fmt(x, d));

export function partName(p: Part): string {
  if (p.kind === 'plate') return `лист ${f(p.w, 1)}×${f(p.h, 1)} мм`;
  if (p.kind === 'ibeam') return `двутавр №${p.no}`;
  if (p.kind === 'channel') return `швеллер №${p.no}`;
  return `уголок ${p.no.replace(/x/g, '×')}`;
}

export function compositeDoc(r: SectionResult, opts: { explain?: boolean; M?: number } = {}): Doc {
  const steps: Step[] = [];
  const ex = (bl: Block[], ...c: Inline[]) => {
    if (opts.explain) bl.push({ k: 'p', cls: 'explain', c });
  };
  const idx = (i: number) => String(i + 1);

  // 1. Части сечения.
  {
    const items: Inline[][] = r.parts.map((p) => [
      `${idx(p.index)}. ${partName(p.part)}: `,
      v('A'),
      sub(idx(p.index)),
      ` = ${f(p.A)} см², центр тяжести (`,
      f(p.X, 3),
      '; ',
      f(p.Y, 3),
      ') см, ',
      v('I'),
      sub('x'),
      ` = ${f(p.Ix)}, `,
      v('I'),
      sub('y'),
      ` = ${f(p.Iy)}`,
      ...(p.Ixy ? [', ', v('I'), sub('xy'), ` = ${f(p.Ixy)}`] : []),
      ' см⁴',
    ]);
    const bl: Block[] = [
      { k: 'p', c: ['Выбираем вспомогательные оси: начало — в точке, от которой заданы положения частей, ось ', v('y'), ' — вверх. Собственные характеристики профилей — по сортаменту, с учётом разворота.'] },
      { k: 'ul', items },
    ];
    ex(
      bl,
      'При развороте профиля на 90° его моменты инерции относительно горизонтальной и вертикальной осей меняются местами, а центробежный момент меняет знак; при зеркальном отражении меняет знак только центробежный момент. Центробежный момент есть только у уголков — у двутавра, швеллера и листа собственные оси являются осями симметрии.',
    );
    steps.push({ title: 'Составные части сечения', blocks: bl });
  }

  // 2. Центр тяжести.
  {
    const sx = r.parts.map((p) => `${f(p.A)}·${f(p.X, 3)}`).join(' + ');
    const sy = r.parts.map((p) => `${f(p.A)}·${f(p.Y, 3)}`).join(' + ');
    const bl: Block[] = [
      {
        k: 'eq',
        lines: [
          { c: [v('A'), ' = Σ', v('A'), sub('i'), ' = ', f(r.A), ' см²'] },
          { c: [v('x'), sub('C'), ' = Σ', v('A'), sub('i'), v('x'), sub('i'), '/', v('A'), ' = (', sx, ')/', f(r.A), ' = ', f(r.xc, 3), ' см'] },
          { c: [v('y'), sub('C'), ' = Σ', v('A'), sub('i'), v('y'), sub('i'), '/', v('A'), ' = (', sy, ')/', f(r.A), ' = ', f(r.yc, 3), ' см'] },
        ],
      },
    ];
    ex(bl, 'Если у сечения есть вертикальная ось симметрии, центр тяжести лежит на ней, и считать нужно только y_C.');
    steps.push({ title: 'Центр тяжести сечения', blocks: bl });
  }

  // 3. Моменты инерции.
  {
    const termsX = r.parts.map((p) => `(${f(p.Ix)} + ${f(p.A)}·${fp(p.Y - r.yc)}²)`).join(' + ');
    const termsY = r.parts.map((p) => `(${f(p.Iy)} + ${f(p.A)}·${fp(p.X - r.xc)}²)`).join(' + ');
    const lines: { num?: boolean; c: Inline[] }[] = [
      { c: [v('I'), sub('X'), ' = Σ(', v('I'), sub('xi'), ' + ', v('A'), sub('i'), v('a'), sub('i'), '²) = ', termsX, ' = ', f(r.Ix), ' см⁴'] },
      { c: [v('I'), sub('Y'), ' = Σ(', v('I'), sub('yi'), ' + ', v('A'), sub('i'), v('b'), sub('i'), '²) = ', termsY, ' = ', f(r.Iy), ' см⁴'] },
      { c: [v('I'), sub('XY'), ' = Σ(', v('I'), sub('xyi'), ' + ', v('A'), sub('i'), v('a'), sub('i'), v('b'), sub('i'), ') = ', f(r.Ixy), ' см⁴'] },
    ];
    const bl: Block[] = [{ k: 'eq', lines }];
    ex(bl, 'Теорема о параллельном переносе осей: момент инерции относительно оси, параллельной центральной оси фигуры, больше центрального на A·a², где a — расстояние между осями (a_i = y_i − y_C, b_i = x_i − x_C).');
    steps.push({ title: 'Центральные моменты инерции', blocks: bl });
  }

  // 4. Главные оси.
  {
    const bl: Block[] = r.principalXY
      ? [{ k: 'p', c: [v('I'), sub('XY'), ' = 0: центральные оси ', v('X'), ' и ', v('Y'), ' — главные (ось ', v('Y'), ' — ось симметрии). Главные моменты инерции: ', v('I'), sub('X'), ` = ${f(r.Ix)} см⁴, `, v('I'), sub('Y'), ` = ${f(r.Iy)} см⁴.`] }]
      : [
          {
            k: 'eq',
            lines: [
              { c: ['tg 2α = −2', v('I'), sub('XY'), '/(', v('I'), sub('X'), ' − ', v('I'), sub('Y'), ')  ⇒  α = ', f(r.alpha, 2), '°'] },
              { c: [v('I'), sub('max,min'), ' = (', v('I'), sub('X'), ' + ', v('I'), sub('Y'), ')/2 ± √(((', v('I'), sub('X'), ' − ', v('I'), sub('Y'), ')/2)² + ', v('I'), sub('XY'), '²) = ', f(r.Iu), ' и ', f(r.Iv), ' см⁴'] },
            ],
          },
        ];
    ex(bl, 'Главные центральные оси — оси, относительно которых центробежный момент инерции равен нулю, а осевые моменты достигают наибольшего и наименьшего значений. Ось симметрии всегда главная.');
    steps.push({ title: 'Главные центральные оси', blocks: bl });
  }

  // 5. Моменты сопротивления.
  steps.push({
    title: 'Моменты сопротивления изгибу',
    blocks: [
      {
        k: 'eq',
        lines: [
          { c: ['Крайние точки: сверху ', f(r.yTop, 3), ' см, снизу ', f(r.yBottom, 3), ' см, справа ', f(r.xRight, 3), ' см, слева ', f(r.xLeft, 3), ' см от центра тяжести'] },
          { c: [v('W'), sub('X'), ' = ', v('I'), sub('X'), '/', v('y'), sub('max'), ' = ', f(r.Ix), '/', f(Math.max(r.yTop, r.yBottom), 3), ' = ', f(r.Wx), ' см³'] },
          { c: [v('W'), sub('Y'), ' = ', v('I'), sub('Y'), '/', v('x'), sub('max'), ' = ', f(r.Iy), '/', f(Math.max(r.xRight, r.xLeft), 3), ' = ', f(r.Wy), ' см³'] },
        ],
      },
    ],
  });

  // 6. Нейтральный слой и напряжения.
  {
    const M = opts.M ?? 0;
    const top = -1e3 / r.WxTop,
      bottom = 1e3 / r.WxBottom;
    const lines: { num?: boolean; c: Inline[] }[] = [
      { c: [v('σ'), sub('верх'), ' = −', v('M'), '/', v('W'), sub('X,верх'), ',  ', v('W'), sub('X,верх'), ' = ', f(r.WxTop), ' см³', M ? `  = ${f(top * M)} МПа` : ''] },
      { c: [v('σ'), sub('низ'), ' = +', v('M'), '/', v('W'), sub('X,низ'), ',  ', v('W'), sub('X,низ'), ' = ', f(r.WxBottom), ' см³', M ? `  = ${f(bottom * M)} МПа` : ''] },
    ];
    const crit = r.critical;
    const bl: Block[] = [
      {
        k: 'p',
        c: r.principalXY
          ? ['Нагрузка действует в вертикальной плоскости, совпадающей с главной плоскостью: нейтральный слой проходит через центр тяжести по оси ', v('X'), ` (на высоте ${f(r.yc, 3)} см от нижней вспомогательной оси). Напряжения σ = −`, v('M'), '·', v('y'), '/', v('I'), sub('X'), ' меняются по высоте линейно (M > 0 — сжаты верхние волокна):']
          : [
              'Плоскость нагрузки не совпадает с главной — изгиб косой. Нейтральная линия проходит через центр тяжести: ',
              v('y'),
              ' = (',
              v('I'),
              sub('XY'),
              '/',
              v('I'),
              sub('Y'),
              ')·',
              v('x'),
              `, наклон ${f(r.neutralAngle, 2)}° к оси X.`,
            ],
      },
      { k: 'eq', lines },
      {
        k: 'p',
        c: [
          'Наиболее нагруженная точка — самая удалённая от нейтрального слоя: (',
          f(crit.x, 3),
          '; ',
          f(crit.y, 3),
          ') см от центра тяжести, ',
          crit.sigmaPerM > 0 ? 'растяжение' : 'сжатие',
          M ? ` σ = ${f(crit.sigmaPerM * M)} МПа.` : ` σ = ${f(Math.abs(crit.sigmaPerM), 3)}·M МПа (M — в кН·м).`,
        ],
      },
    ];
    ex(bl, 'Напряжения пропорциональны расстоянию от нейтрального слоя, поэтому опасны точки на самом большом удалении. Ниже нейтрального слоя знак напряжений противоположен знаку выше.');
    steps.push({ title: 'Нейтральный слой и эпюра нормальных напряжений', blocks: bl });
  }

  steps.push({
    title: 'Ответ',
    blocks: [
      {
        k: 'answer',
        rows: [
          { kind: 'main', val: [v('y'), sub('C'), ` = ${f(r.yc, 3)} см`], note: 'нейтральный слой — через центр тяжести' },
          { kind: 'main', val: [v('I'), sub('X'), ` = ${f(r.Ix)} см⁴, `, v('I'), sub('Y'), ` = ${f(r.Iy)} см⁴`], note: r.principalXY ? 'главные моменты инерции' : `главные: ${f(r.Iu)} и ${f(r.Iv)} см⁴` },
          { kind: 'main', val: [v('W'), sub('X'), ` = ${f(r.Wx)} см³, `, v('W'), sub('Y'), ` = ${f(r.Wy)} см³`], note: 'моменты сопротивления' },
        ],
      },
    ],
  });
  return { steps };
}
