const part = (kind: CPart['kind'], p: Record<string, number>, s: 1 | -1 = 1, k = 1, pts?: [number, number][]): CPart => ({
  kind,
  p,
  s,
  k,
  ...(pts ? { pts } : {}),
});
const rect = (x: number, y: number, w: number, h: number) => part('rect', { x, y, w, h });
/** Однородный брусок (стержень) весом W между точками a и b: погонный вес W/L. */
const bar = (a: [number, number, number], b: [number, number, number], W = 0) => {
  const L = Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
  return part('line', { x1: a[0], y1: a[1], z1: a[2], x2: b[0], y2: b[1], z2: b[2] }, 1, W ? W / L : 1);
};
const pt = (x: number, y: number, z: number, w: number) => part('point', { x, y, z, w });

