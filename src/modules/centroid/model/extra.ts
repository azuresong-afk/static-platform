/**
 * Пункт 26, «Центр тяжести»: обратные задачи §9 — найти размер или точку по условию на центр тяжести.
 *
 *  - hang   9.13 — трапеция, отрезанная от прямоугольника прямой DE, висит на вершине E и AD горизонтальна;
 *  - notch  9.14 — из прямоугольника вырезан равнобедренный треугольник AEB: E — центр тяжести остатка;
 *  - carry  9.15 — четверо несут треугольную пластину: двое за вершины, двое — на сторонах у третьей вершины;
 *  - halves 9.25 — две половины цилиндра, стянутые нитью с гирями: наименьший вес гирь.
 */
import { ansB, bold, eqB, fail, sg, stepB, stepEx, type AskDef, type ExtraOut } from '../../../shared/extra';
import { solveCentroid, type CPart } from './centroid';

const pos = (...x: number[]) => x.every((v) => v > 0 && Number.isFinite(v));
const done = (o: Omit<ExtraOut, 'ok' | 'errors'>): ExtraOut => ({ ok: true, errors: [], ...o });
const part = (kind: CPart['kind'], p: Record<string, number>, s: 1 | -1 = 1): CPart => ({ kind, p, s, k: 1 });

/* ---------- 9.13 ---------- */
const A_HANG: AskDef = {
  id: 'hang',
  title: '9.13: трапеция висит на вершине E — сторона AD горизонтальна',
  hint: 'Прямоугольник ABCD (AD = a — нижняя сторона, AB — правая); прямая DE отрезает треугольник DCE, E — на верхней стороне BC.',
  n: { a: 1, h: 1.5 },
  fields: [
    { k: 'a', label: 'сторона AD = a' },
    { k: 'h', label: 'высота AB (на ответ не влияет)' },
  ],
  solve: (q, ex) => {
    const { a, h } = q.n;
    if (!pos(a, h)) return fail(['Размеры — положительные.']);
    const t = (a * (Math.sqrt(3) - 1)) / 2;
    // Проверка через центр тяжести: D(0, 0), A(a, 0), B(a, h), C(0, h), E(a − t, h).
    const r = solveCentroid({
      mode: 'area',
      parts: [part('rect', { x: 0, y: 0, w: a, h }), part('tri', { x1: 0, y1: 0, x2: 0, y2: h, x3: a - t, y3: h }, -1)],
    });
    return done({
      vals: { BE: t, xC: r.c ? r.c[0] : NaN },
      steps: [
        stepEx(
          ex,
          'Условие',
          'Тело, подвешенное за точку, висит так, что центр тяжести лежит на вертикали через точку подвеса. AD горизонтальна, значит, центр тяжести трапеции на одной вертикали с E.',
          eqB('x_C = x_E'),
        ),
        stepEx(
          ex,
          'Центр тяжести трапеции',
          'Отсчитываем от стороны AB (прямой угол трапеции): основания a и t = BE, центр тяжести прямоугольной трапеции — на расстоянии (a² + at + t²)/(3(a + t)) от AB.',
          eqB('(a² + at + t²)/(3(a + t)) = t  ⇒  2t² + 2at − a² = 0', `t = a(√3 − 1)/2 = ${sg(t)}`),
        ),
        stepB('Проверка', eqB(`прямоугольник минус треугольник DCE: x_C = ${sg(r.c ? r.c[0] : NaN)}, x_E = a − t = ${sg(a - t)}`)),
        stepB('Ответ', ansB([bold(`BE = ${sg(t)}`), `= ${sg(t / a)}·a, от высоты не зависит`])),
      ],
      plot: {
        xl: 'x',
        yl: 'y',
        equal: true,
        series: [
          {
            name: 'трапеция ABED',
            pts: [
              [0, 0],
              [a, 0],
              [a, h],
              [a - t, h],
              [0, 0],
            ],
          },
          {
            name: 'отрезано',
            pts: [
              [0, 0],
              [0, h],
              [a - t, h],
            ],
            cls: 'rl-e',
          },
        ],
        marks: [{ x: a - t, y: h, label: 'E' }, ...(r.c ? [{ x: r.c[0], y: r.c[1], label: 'C' }] : [])],
      },
    });
  },
};

/* ---------- 9.14 ---------- */
const A_NOTCH: AskDef = {
  id: 'notch',
  title: '9.14: вырез — треугольник AEB, E — центр тяжести остатка',
  hint: 'Из прямоугольника a × H (квадрат: H = a) вырезан равнобедренный треугольник с основанием AB (нижняя сторона) и вершиной E.',
  n: { a: 1, H: 1 },
  fields: [
    { k: 'a', label: 'ширина AB = a' },
    { k: 'H', label: 'высота H (квадрат — H = a)' },
  ],
  solve: (q, ex) => {
    const { a, H } = q.n;
    if (!pos(a, H)) return fail(['Размеры — положительные.']);
    const y = (H * (3 - Math.sqrt(3))) / 2;
    const r = solveCentroid({
      mode: 'area',
      parts: [part('rect', { x: 0, y: 0, w: a, h: H }), part('tri', { x1: 0, y1: 0, x2: a, y2: 0, x3: a / 2, y3: y }, -1)],
    });
    return done({
      vals: { xE: a / 2, yE: y, yC: r.c ? r.c[1] : NaN },
      steps: [
        stepEx(
          ex,
          'Симметрия',
          'Фигура симметрична относительно вертикали через середину AB — центр тяжести и вершина E на ней.',
          eqB(`x_E = a/2 = ${sg(a / 2)}`),
        ),
        stepEx(
          ex,
          'Условие y_C = y_E',
          'Метод отрицательных площадей: прямоугольник aH с центром на высоте H/2 минус треугольник ay/2 с центром на высоте y/3.',
          eqB('(aH·H/2 − (ay/2)(y/3))/(aH − ay/2) = y', 'y²/3 − Hy + H²/2 = 0  ⇒  y = H(3 − √3)/2', `y_E = ${sg(y)}`),
        ),
        stepB('Проверка', eqB(`центр тяжести остатка: y_C = ${sg(r.c ? r.c[1] : NaN)}`)),
        stepB('Ответ', ansB([bold(`x_E = ${sg(a / 2)}, y_E = ${sg(y)}`), `y_E = ${sg(y / H)}·H`])),
      ],
      plot: {
        xl: 'x',
        yl: 'y',
        equal: true,
        series: [
          {
            name: 'квадрат',
            pts: [
              [0, 0],
              [a, 0],
              [a, H],
              [0, H],
              [0, 0],
            ],
          },
          {
            name: 'вырез AEB',
            pts: [
              [0, 0],
              [a / 2, y],
              [a, 0],
            ],
            cls: 'rl-e',
          },
        ],
        marks: [{ x: a / 2, y, label: 'E = C' }],
      },
    });
  },
};

/* ---------- 9.15 ---------- */
const A_CARRY: AskDef = {
  id: 'carry',
  title: '9.15: четверо несут треугольную пластину поровну',
  hint: 'Вершины A, B, C; двое держат вершины B и C, двое — стороны AB и AC на расстоянии t·AB и t·AC от вершины A.',
  n: { xA: 0, yA: 3, xB: 0, yB: 0, xC: 4, yC: 0 },
  fields: [
    { k: 'xA', label: 'x_A', neg: true },
    { k: 'yA', label: 'y_A', neg: true },
    { k: 'xB', label: 'x_B', neg: true },
    { k: 'yB', label: 'y_B', neg: true },
    { k: 'xC', label: 'x_C', neg: true },
    { k: 'yC', label: 'y_C', neg: true },
  ],
  solve: (q, ex) => {
    const n = q.n;
    const A = [n.xA, n.yA],
      B = [n.xB, n.yB],
      C = [n.xC, n.yC];
    const S = Math.abs((B[0] - A[0]) * (C[1] - A[1]) - (C[0] - A[0]) * (B[1] - A[1])) / 2;
    if (!(S > 1e-12)) return fail(['Вершины лежат на одной прямой.']);
    const t = 1 / 3;
    const K = [A[0] + t * (B[0] - A[0]), A[1] + t * (B[1] - A[1])],
      L = [A[0] + t * (C[0] - A[0]), A[1] + t * (C[1] - A[1])];
    const G = [(A[0] + B[0] + C[0]) / 3, (A[1] + B[1] + C[1]) / 3];
    const M = [(B[0] + C[0] + K[0] + L[0]) / 4, (B[1] + C[1] + K[1] + L[1]) / 4];
    return done({
      vals: { t, dx: M[0] - G[0], dy: M[1] - G[1] },
      steps: [
        stepEx(
          ex,
          'Условие',
          'Четыре равные силы P/4 уравновешивают вес P, приложенный в центре тяжести пластины, только если их равнодействующая проходит через него: центр тяжести четырёх равных «грузов» в точках опоры совпадает с центром тяжести треугольника.',
          eqB('(r_B + r_C + r_K + r_L)/4 = (r_A + r_B + r_C)/3', 'r_K = r_A + t(r_B − r_A),  r_L = r_A + t(r_C − r_A)'),
        ),
        stepB(
          'Решение',
          eqB(
            '3(r_B + r_C) + 3(2r_A + t(r_B + r_C − 2r_A)) = 4(r_A + r_B + r_C)',
            '3t(r_B + r_C − 2r_A) = r_B + r_C − 2r_A  ⇒  t = 1/3 для любого треугольника',
          ),
        ),
        stepB('Проверка', eqB(`центр тяжести пластины (${sg(G[0])}; ${sg(G[1])}), четырёх точек опоры (${sg(M[0])}; ${sg(M[1])})`)),
        stepB('Ответ', ansB([bold('t = 1/3'), 'на трети длины каждой стороны от третьей вершины'])),
      ],
      plot: {
        xl: 'x',
        yl: 'y',
        equal: true,
        series: [{ name: 'пластина', pts: [A, B, C, A] as [number, number][] }],
        marks: [
          { x: B[0], y: B[1], label: 'B' },
          { x: C[0], y: C[1], label: 'C' },
          { x: K[0], y: K[1], label: 'K' },
          { x: L[0], y: L[1], label: 'L' },
          { x: G[0], y: G[1], label: 'центр' },
        ],
      },
    });
  },
};

/* ---------- 9.25 ---------- */
const A_HALVES: AskDef = {
  id: 'halves',
  title: '9.25: половины цилиндра, стянутые нитью с гирями',
  hint: 'Цилиндр весом Q лежит на боку, плоскость раздела половин вертикальна; нить перекинута через цилиндр, на концах — гири весом P.',
  n: { Q: 1, r: 1 },
  fields: [
    { k: 'Q', label: 'вес цилиндра Q' },
    { k: 'r', label: 'радиус r (на ответ не влияет)' },
  ],
  solve: (q, ex) => {
    const { Q, r } = q.n;
    if (!pos(Q, r)) return fail(['Данные — положительные.']);
    const e = (4 * r) / (3 * Math.PI);
    const P = (2 * Q) / (3 * Math.PI);
    return done({
      vals: { P, e },
      steps: [
        stepEx(
          ex,
          'Центр тяжести половины',
          'Половина цилиндра — полукруг в сечении: центр тяжести отстоит от плоскости раздела на 4r/(3π).',
          eqB(`e = 4r/(3π) = ${sg(e)}`),
        ),
        stepEx(
          ex,
          'Опрокидывание половины',
          'Половина стремится повернуться вокруг нижней образующей (точки опоры на плоскости). Нить действует на половину силой P по горизонтали вверху (на высоте 2r, к другой половине) и силой P вниз сбоку (на расстоянии r от плоскости раздела).',
          eqB('момент нити: P·2r − P·r = P·r (прижимает половины)', 'момент веса: (Q/2)·4r/(3π) (раскрывает)'),
        ),
        stepB('Условие покоя', eqB('P·r ≥ (Q/2)·4r/(3π)  ⇒  P ≥ 2Q/(3π)', `P_min = ${sg(P)}`)),
        stepB('Ответ', ansB([bold(`P = 2Q/(3π) = ${sg(P)}`), 'наименьший вес гирь'])),
      ],
    });
  },
};

export const CENTROID_ASKS: AskDef[] = [A_HANG, A_NOTCH, A_CARRY, A_HALVES];
