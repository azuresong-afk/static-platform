/** Решения задач «сложение скоростей с условием»: вымпел, встреча, ветер, полигон, переправа, лента, винт. */
import { b, sub, v, type AnswerRow, type Block, type Doc, type Inline, type Step } from '../../../shared/doc';
import { fmt } from '../../../shared/format';
import type { CondProblem, CondResult } from '../model/cond';

const f = (x: number) => fmt(x, 4);

export function condDoc(pr: CondProblem, r: CondResult, opts: { explain?: boolean } = {}): Doc {
  if (!r.ok)
    return {
      steps: [
        {
          title: 'Данные',
          blocks: [
            { k: 'badge', tone: 'bad', text: 'проверьте данные' },
            { k: 'ul', items: r.errors.map((x) => [x]) },
          ],
        },
      ],
    };
  const o = r.out;
  const steps: Step[] = [];
  const ex = (bl: Block[], ...c: Inline[]) => {
    if (opts.explain) bl.push({ k: 'p', cls: 'explain', c });
  };
  const step = (title: string, lines: Inline[][], ...expl: Inline[]) => {
    const bl: Block[] = [{ k: 'eq', lines: lines.map((c) => ({ c })) }];
    if (expl.length) ex(bl, ...expl);
    steps.push({ title, blocks: bl });
  };
  const ans = (rows: AnswerRow[]) => steps.push({ title: 'Ответ', blocks: [{ k: 'answer', rows }] });
  switch (r.kind) {
    case 'flag': {
      const opp = o.opp === 1;
      step(
        'Движение вымпела',
        [
          ['вымпел сохраняет горизонтальную скорость самолёта v₁ и падает без начальной вертикальной скорости: h = gT²/2  ⇒  T = √(2h/g) = ', b(f(o.T)), ' с'],
          [`за это время вымпел пролетает по горизонтали v₁T = ${f(o.drop)}`],
          opp
            ? ['корабль идёт навстречу: за T он проходит vT = ', f(o.v * o.T), ';  l = v₁T + vT = (v₁ + v)T = ', b(f(o.l))]
            : ['корабль идёт тем же курсом: за T он проходит vT = ', f(o.v * o.T), ';  l = v₁T − vT = (v₁ − v)T = ', b(f(o.l))],
        ],
        'Вымпел должен упасть на корабль: его горизонтальное перемещение относительно воды равно перемещению корабля плюс расстояние l между ними в момент сброса. Если l < 0, самолёт должен находиться впереди корабля (он медленнее).',
      );
      ans([{ kind: 'main', val: [v('l'), ` = ${f(o.l)}`], note: `по горизонтали, ${opp ? '(v₁ + v)' : '(v₁ − v)'}√(2h/g); время падения ${f(o.T)} с` }]);
      break;
    }
    case 'meet': {
      step(
        'Условие встречи',
        [
          ['за время T корабль проходит v₀T, катер — v₁T; по теореме синусов для треугольника ABM:  sin β / v₀ = cos ψ₀ / v₁'],
          ['sin β = (v₀/v₁)·cos ψ₀ = ', f(o.sinB), '  ⇒  β = ', b(`${f(o.beta)}°`)],
        ],
        'Катер и корабль встретятся в точке M, если пути v₁T и v₀T за одно и то же время T образуют с отрезком AB треугольник. Угол β катера с линией BA находится по теореме синусов.',
      );
      step('Время до встречи', [
        ['(v₀² − v₁²)T² − 2v₀ l sin ψ₀·T + l² = 0  ⇒  T = l / (v₀ sin ψ₀ + √(v₁² − v₀² cos² ψ₀)) = ', b(f(o.T)), ' с'],
        [`проверка: T = (l/v₀)·sin β / cos(ψ₀ − β) = ${f(o.Tsine)} с`],
        [`точка встречи M = (${f(o.Mx)}; ${f(o.My)}), B = (${f(o.Bx)}; ${f(o.By)}), A — начало; корабль идёт вдоль оси y`],
      ]);
      ans([{ kind: 'main', val: [`β = ${f(o.beta)}°, T = ${f(o.T)} с`], note: 'угол курса катера с BA и время до встречи' }]);
      break;
    }
    case 'wind': {
      step(
        'Путевые скорости',
        [
          [`по ветру: l/t₁ = ${f(o.g1)} = v + V`],
          [`против ветра: l/t₂ = ${f(o.g2)} = v − V`],
          ['v = (l/2)(1/t₁ + 1/t₂) = ', b(f(o.v)), ' м/с = ', b(f(o.vkmh)), ' км/ч'],
          ['V = (l/2)(1/t₁ − 1/t₂) = ', b(f(o.V)), ' м/с = ', b(f(o.Vkmh)), ' км/ч'],
        ],
        'Собственная скорость самолёта v — относительно воздуха, скорость ветра V — переносная; путевая скорость вдоль ветра v + V, против ветра v − V. Сложив и вычтя равенства, получаем v и V.',
      );
      ans([
        {
          kind: 'main',
          val: [`v = ${f(o.v)} м/с (${f(o.vkmh)} км/ч), V = ${f(o.V)} м/с (${f(o.Vkmh)} км/ч)`],
          note: o.tail === 1 ? 'ветер попутный на первом проходе' : 'на первом проходе ветер встречный',
        },
      ]);
      break;
    }
    case 'poly': {
      step(
        'Построение',
        [
          [`треугольник: B = (0; 0), C = (${f(Number(pr.p.a ?? '0'))}; 0), A = (${f(o.Ax)}; ${f(o.Ay)})`],
          [`путевые скорости по сторонам (облёт B → C → A → B): ${f(o.g1)}, ${f(o.g2)}, ${f(o.g3)}`],
          [
            'каждый вектор путевой скорости = собственная скорость u + ветер W, |u| = v; поэтому концы трёх векторов, отложенных от общей точки M, лежат на окружности радиуса v с центром в конце вектора W',
          ],
        ],
        'Ветер W одинаков на всех участках, а собственная скорость v по модулю неизменна. Значит, все три путевые скорости удалены от одной точки (конца вектора W) на одно и то же расстояние v — она находится как центр окружности, проведённой через три точки.',
      );
      step('Результат', [
        ['центр окружности: W = (', f(o.Wx), '; ', f(o.Wy), '),  |W| = ', b(f(o.W)), ', направление ', f(o.Wdir), '° от оси x (по стороне BC)'],
        ['радиус окружности: v = ', b(f(o.v))],
      ]);
      ans([{ kind: 'main', val: [v('v'), ` = ${f(o.v)}, `, v('W'), ` = ${f(o.W)}`], note: 'собственная скорость самолёта и скорость ветра' }]);
      break;
    }
    case 'river': {
      step(
        'Снос и ширина',
        [
          ['курс перпендикулярно берегам: ширина l = u·t₁, снос s = v·t₁  ⇒  v = s/t₁ = ', b(f(o.v))],
          ['курс против течения под углом α так, что путь AB перпендикулярен берегам: l = √(u² − v²)·t₂'],
          ['u²t₁² = (u² − v²)t₂²  ⇒  u = v·t₂/√(t₂² − t₁²) = ', b(f(o.u))],
          ['l = u·t₁ = ', b(f(o.l)), `;  угол курса α = arcsin(v/u) = ${f(o.alpha)}°`],
        ],
        'Скорость лодки относительно берега — сумма скорости относительно воды u и скорости течения v. Когда курс перпендикулярен берегам, течение только сносит лодку; чтобы попасть в точку на перпендикуляре, нужно держать курс под углом α, так чтобы составляющая u·sin α гасила течение.',
      );
      ans([{ kind: 'main', val: [`l = ${f(o.l)}, u = ${f(o.u)}, v = ${f(o.v)}`], note: 'ширина реки, скорость лодки относительно воды, скорость течения' }]);
      break;
    }
    case 'tape': {
      step(
        'Колебание по виду кривой',
        [
          ['лента движется равномерно, поэтому длина волны λ = vT  ⇒  T = λ/v = ', f(o.T), ' с'],
          ['ω = 2π/T = ', b(`${f(o.wOverPi)}π`), ' = ', f(o.w), ' с⁻¹'],
          ['y = A sin ωt = ', b(`${f(o.A)} sin(${f(o.wOverPi)}πt)`)],
        ],
        'Тело колеблется поперёк движения ленты и вычерчивает на ней синусоиду: смещение вдоль ленты — это vt, поэтому одному периоду колебаний соответствует длина волны λ = vT. Начало синусоиды отвечает t = 0, значит, фаза нулевая.',
      );
      ans([{ kind: 'main', val: [`y = ${f(o.A)} sin(${f(o.wOverPi)}πt)`], note: `период ${f(o.T)} с` }]);
      break;
    }
    case 'screw': {
      step(
        'Перемещение указателя',
        [
          [
            `за один оборот оси ${o.opp === 1 ? 'части A и B перемещаются в разные стороны: ход указателя h₁ + h₂' : 'гайка C сдвигает ось на h₁, а элемент D относительно оси — на h₂ в ту же сторону: разность h₁ − h₂'} = ${f(o.per)}`,
          ],
          [`при повороте на 1/n оборота (n = ${f(o.n)}):  s = ${o.opp === 1 ? '(h₁ + h₂)' : '(h₁ − h₂)'}/n = `, b(f(o.s))],
        ],
        'Ось при каждом обороте уходит из неподвижной гайки на шаг h₁, а элемент D с указателем смещается относительно оси на шаг h₂. При одинаковом направлении нарезок результат — разность, при разном — сумма.',
      );
      ans([{ kind: 'main', val: [v('s'), ` = ${f(o.s)}`], note: 'перемещение указателя' }]);
      break;
    }
  }
  void sub;
  return { steps };
}
