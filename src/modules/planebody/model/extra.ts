import { parseNum } from '../../../shared/format';
import { ansB, bold, eqB, fail, parB, sample, sg, stepB, stepEx, type AskDef, type ExtraOut } from '../../../shared/extra';

const G = 9.81;
const D2R = Math.PI / 180;
const pos = (...x: number[]) => x.every((v) => v > 0 && Number.isFinite(v));
const done = (o: Omit<ExtraOut, 'ok' | 'errors'>): ExtraOut => ({ ok: true, errors: [], ...o });

/* ---------- 37.1–37.3 ---------- */
export function parseBodies(src: string): number[][] | string {
  const rows = src
    .split(/[;\n]/)
    .map((x) => x.trim())
    .filter(Boolean)
    .map((x) => x.split(':').map((y) => parseNum(y.trim())));
  if (!rows.length || rows.length > 8) return 'тела: от одного до восьми, через «;»';
  for (const r of rows) if (r.length !== 7 || !r.every(Number.isFinite)) return 'каждое тело — семь чисел «m : J_C : x : y : v_x : v_y : ω»';
  if (rows.some((r) => r[0] < 0 || r[1] < 0)) return 'масса и момент инерции — неотрицательные';
  return rows;
}
const A_KMOM: AskDef = {
  id: 'kmom',
  title: '37.1–37.3: кинетический момент тел в плоском движении относительно оси',
  hint: 'Каждое тело: масса m, момент инерции J_C относительно оси через его центр масс, положение центра масс (x, y) относительно точки O, скорость центра масс (v_x, v_y), угловая скорость ω (против часовой стрелки — плюс).',
  n: {},
  s: { B: '5,097 : 0,2294 : 0 : 0,3 : 1,885 : 0 : -6,283' },
  fields: [{ k: 'B', label: 'тела «m : J_C : x : y : v_x : v_y : ω» через «;»', text: true }],
  solve: (q, ex) => {
    const rows = parseBodies(q.s.B);
    if (typeof rows === 'string') return fail([rows]);
    let K = 0,
      Kc = 0,
      M = 0,
      px = 0,
      py = 0,
      mx = 0,
      my = 0;
    const lines: string[] = [];
    rows.forEach(([m, J, x, y, vx, vy, w], i) => {
      const own = J * w,
        orb = m * (x * vy - y * vx);
      K += own + orb;
      Kc += own;
      M += m;
      px += m * vx;
      py += m * vy;
      mx += m * x;
      my += m * y;
      lines.push(`тело ${i + 1}: J_C ω = ${sg(own)},  m(x v_y − y v_x) = ${sg(orb)}`);
    });
    // кинетический момент относительно центра масс системы (относительное движение)
    const xc = M > 0 ? mx / M : 0,
      yc = M > 0 ? my / M : 0;
    const Krel = K - (xc * py - yc * px);
    const steps = [
      stepEx(ex, 'Кинетический момент тела в плоском движении', 'Количества движения точек тела приводятся к центру масс: вектор m·v_C и пара с моментом J_C ω. Поэтому K_O = J_C ω + момент вектора m·v_C относительно O.', eqB('K_O = J_C ω + m (x_C v_Cy − y_C v_Cx)', ...lines)),
      stepB('Сумма', eqB(`K_O = ${sg(K)}`, `Σ J_C ω = ${sg(Kc)} (моменты «собственного вращения»)`, `относительно центра масс системы: K_C = ${sg(Krel)}`)),
      stepEx(ex, 'Мгновенная ось', 'Для одного тела относительно мгновенного центра скоростей P: K_P = J_P ω = (J_C + m·CP²) ω.', parB('Знак K — направление вращения: плюс — против часовой стрелки.')),
      stepB('Ответ', ansB([[bold(`K_O = ${sg(K)}`)], 'кинетический момент относительно оси, проходящей через O'], [`|K_O| = ${sg(Math.abs(K))}`, 'модуль', 'aux'])),
    ];
    return done({ vals: { K, Kabs: Math.abs(K), Kc, Krel }, steps });
  },
};

