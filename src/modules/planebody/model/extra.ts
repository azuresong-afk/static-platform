const A_REDUCE: AskDef = {
  id: 'reduce',
  title: '43.9: замена стержня двумя точечными массами на концах — силы инерции',
  hint: 'Масса стержня m заменена массами в концах A и B так, что их сумма равна m, а центр масс совпадает с C. Сравнить главный момент сил инерции приведённых масс и стержня при угловом ускорении ε.',
  n: { m: 1, rho: 0.3, a: 0.4, b: 0.6, eps: 1 },
  fields: [
    { k: 'm', label: 'масса m' },
    { k: 'rho', label: 'радиус инерции ρ относительно C' },
    { k: 'a', label: 'CA = a' },
    { k: 'b', label: 'CB = b' },
    { k: 'eps', label: 'угловое ускорение ε', neg: true },
  ],
  solve: (q, ex) => {
    const { m, rho, a, b, eps } = q.n;
    if (!pos(m, rho, a, b)) return fail(['m, ρ, a, b > 0.']);
    const mA = (m * b) / (a + b),
      mB = (m * a) / (a + b);
    const Mrod = -m * rho * rho * eps,
      Mpts = -(mA * a * a + mB * b * b) * eps;
    const dM = Mpts - Mrod;
    const steps = [
      stepEx(ex, 'Приведённые массы', 'Сумма масс m и центр масс в C: m_A·a = m_B·b.', eqB(`m_A = m b/(a + b) = ${sg(mA)},  m_B = m a/(a + b) = ${sg(mB)}`)),
      stepEx(ex, 'Главные векторы', 'Главный вектор сил инерции −M·a_C зависит только от общей массы и ускорения центра масс — они совпадают.', parB('Φ = −m·a_C у обеих систем.')),
      stepB('Главные моменты относительно C', eqB(`стержень: M_C = −m ρ² ε = ${sg(Mrod)}`, `точки: M_C = −(m_A a² + m_B b²) ε = −m a b ε = ${sg(Mpts)}`, `разность: m(ρ² − ab)ε = ${sg(-dM)}`)),
      stepB('Ответ', ansB([[bold(Math.abs(rho * rho - a * b) < 1e-12 ? 'главные моменты равны (ρ² = ab)' : `главные моменты отличаются на ${sg(Math.abs(dM))}`)], 'главные векторы геометрически равны; моменты равны лишь при ρ² = ab'])),
    ];
    return done({ vals: { Mrod, Mpts, dM }, steps });
  },
};

