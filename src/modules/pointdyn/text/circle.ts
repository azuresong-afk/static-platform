/** Решение: движение по окружности в вертикальной плоскости — интеграл энергии, реакция связи, отрыв, полный оборот. */
import { b, sub, v, type AnswerRow, type Block, type Doc, type Inline, type Step } from '../../../shared/doc';
import { fmt } from '../../../shared/format';
import { LINK_NAME } from '../draw/circle';
import type { CircleProblem, CircleResult } from '../model/circle';

const f = (x: number) => fmt(x, 4);
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const rad = (a: number) => (a * Math.PI) / 180;
/** Угол в окне (−180°; 180°]: «−» — слева от нижней точки. */
const norm = (a: number) => {
  const x = ((a % 360) + 360) % 360;
  return x > 180 ? x - 360 : x;
};

export function circleDoc(pr: CircleProblem, r: CircleResult, opts: { explain?: boolean } = {}): Doc {
  const steps: Step[] = [];
  const ex = (bl: Block[], ...c: Inline[]) => {
    if (opts.explain) bl.push({ k: 'p', cls: 'explain', c });
  };
  if (!r.ok) {
    steps.push({
      title: 'Данные',
      blocks: [
        { k: 'badge', tone: 'bad', text: 'проверьте данные' },
        { k: 'ul', items: r.errors.map((x) => [x]) },
      ],
    });
    return { steps };
  }
  const FU = pr.byWeight ? 'кГ' : 'Н';
  const sp = pr.spring && pr.c > 0;
  /** Смысл N для связи: натяжение, давление на поверхность, реакция стержня. */
  const meaning = (N: number): string => {
    if (pr.link === 'thread') return N >= 0 ? `натяжение нити T = ${f(N)} ${FU}` : 'нить не натянута';
    if (pr.link === 'inner') return N >= 0 ? `давление на поверхность ${f(N)} ${FU} (от центра)` : 'точка не прижата к поверхности';
    if (pr.link === 'outer') return N <= 0 ? `давление на поверхность ${f(-N)} ${FU} (к центру)` : 'точка не прижата к поверхности';
    return N >= 0
      ? `реакция ${f(N)} ${FU} направлена к центру (стержень растянут; давление точки на трубку или проволоку — от центра)`
      : `реакция ${f(-N)} ${FU} направлена от центра (стержень сжат; давление точки на трубку или проволоку — к центру)`;
  };
  const h = (phi: number) => pr.R * (1 - Math.cos(rad(phi)));
  /** Угол от нижней и от верхней точки. */
  const ang = (phi: number) => `${f(norm(phi))}° (${f(180 - Math.abs(norm(phi)))}° от верхней точки)`;
  // 1. Связь и силы.
  {
    const items: Inline[][] = [
      [`окружность радиуса R = ${f(pr.R)} в вертикальной плоскости; связь — ${LINK_NAME[pr.link]}`],
      [`масса m = ${pr.byWeight ? `P/g = ${f(pr.m)}/${f(pr.g)} = ` : ''}${f(r.mass)}; вес P = ${f(r.P)} ${FU}`],
      [
        `начальное положение φ₀ = ${f(pr.phi0)}° (высота над нижней точкой y₀ = R(1 − cos φ₀) = ${f(h(pr.phi0))}), скорость v₀ = ${f(pr.v0)}${pr.v0 ? (pr.v0 > 0 ? ' — в сторону роста φ' : ' — в сторону убывания φ') : ''}`,
      ],
    ];
    if (sp)
      items.push([
        `пружина от точки A(${f(pr.ax)}; ${f(pr.ay)}) (относительно центра): c = ${f(pr.c)}, длина без натяжения L₀ = ${f(pr.L0)}; Π_пр = c(|AM| − L₀)²/2`,
      ]);
    const bl: Block[] = [{ k: 'ul', items }];
    ex(
      bl,
      'Угол φ отсчитывается от нижней точки окружности против часовой стрелки: φ = 0 — внизу, 90° — справа на уровне центра, 180° — вверху. Связь гладкая: её реакция направлена по нормали и работы не совершает, поэтому скорость находится из интеграла энергии.',
    );
    steps.push({ title: 'Связь и силы', blocks: bl });
  }
  // 2. Интеграл энергии и реакция.
  {
    const lines: { c: Inline[] }[] = [
      { c: [v('v'), '² = ', v('v'), '₀² − 2g(', v('y'), ' − ', v('y'), '₀)', sp ? ' − (2/m)(Π_пр − Π_пр₀)' : '', ',  ', v('y'), ' = R(1 − cos φ)'] },
      { c: [v('m'), v('v'), '²/R = ', v('N'), ' − mg cos φ', sp ? ' + F_пр·n' : '', '  ⇒  ', b(`N = mv²/R + mg cos φ${sp ? ' − F_пр·n' : ''}`)] },
    ];
    const bl: Block[] = [{ k: 'eq', lines }];
    bl.push({
      k: 'p',
      c: [
        'N — проекция реакции на направление к центру. ',
        pr.link === 'thread'
          ? 'Для нити это натяжение: нить держит, пока N ≥ 0.'
          : pr.link === 'inner'
            ? 'Точка прижата к внутренней стороне, пока N ≥ 0; давление на поверхность равно N.'
            : pr.link === 'outer'
              ? 'Реакция внешней поверхности направлена от центра: точка прижата, пока N ≤ 0; давление равно −N.'
              : 'Связь двусторонняя: N может быть любого знака.',
      ],
    });
    ex(
      bl,
      'Второй закон Ньютона в проекции на главную нормаль (к центру окружности): m·v²/R — центростремительная сила; сила тяжести даёт проекцию −mg cos φ (в нижней точке она направлена от центра, в верхней — к центру).',
    );
    steps.push({ title: 'Скорость и реакция связи', blocks: bl });
  }
  // 3. Движение: остановка, отрыв, оборот.
  const rows: AnswerRow[] = [];
  {
    const bl: Block[] = [];
    const ev = r.fwd;
    if (r.dir === 0)
      bl.push({ k: 'p', c: ['Скорость равна нулю и касательная сила тоже: точка покоится в положении устойчивого равновесия. ', meaning(r.N0), '.'] });
    else if (ev) {
      const dirTxt = r.dir > 0 ? 'в сторону роста φ' : 'в сторону убывания φ';
      if (r.push)
        bl.push({
          k: 'p',
          c: [
            'Начальное положение — неустойчивое равновесие: касательная сила равна нулю, но при отклонении направлена в сторону отклонения. При ничтожно малом толчке точка уходит из него; считаем, что толчок — в сторону роста φ. В начальном положении: ',
            meaning(r.N0),
            '.',
          ],
        });
      else
        bl.push({
          k: 'p',
          c: [
            `Точка движется ${dirTxt}${pr.v0 === 0 ? ' (из покоя — под действием касательной силы ' + f(r.Ft0) + ' ' + FU + ')' : ''}. В начальном положении: `,
            meaning(r.N0),
            '.',
          ],
        });
      const evText = (e: NonNullable<CircleResult['fwd']>): Inline[] =>
        e.kind === 'round'
          ? [
              'проходит полный оборот: скорость нигде не обращается в нуль',
              pr.link === 'rod' ? '' : ' и связь везде удерживает точку',
              ' — движение периодическое',
            ]
          : e.kind === 'stop' && Math.abs(e.phi - pr.phi0) >= 360 - 1e-9
            ? ['проходит всю окружность и приближается к исходному положению асимптотически: скорость стремится к нулю, а время движения — к бесконечности']
            : e.kind === 'stop'
              ? [`при φ = ${f(norm(e.phi))}° скорость обращается в нуль (высота ${f(h(e.phi))} над нижней точкой); `, meaning(e.N)]
              : [
                  `при φ = ${ang(e.phi)} N = 0 — ${pr.link === 'thread' ? 'нить перестаёт быть натянутой' : 'точка сходит со связи'}: высота ${f(h(e.phi))} над нижней точкой (${f(h(e.phi) - pr.R)} над центром), скорость `,
                  b(`v = ${f(e.v)}`),
                  '. Дальше — свободный полёт по параболе (до нового натяжения нити или удара).',
                ];
      bl.push({ k: 'p', c: ['Вперёд: ', ...evText(ev)] });
      if (r.back) bl.push({ k: 'p', c: ['После остановки точка движется обратно и ', ...evText(r.back)] });
      if (r.zero) {
        bl.push({
          k: 'p',
          c: [
            `При φ = ${ang(r.zero.phi)} N = 0: реакция меняет направление — `,
            r.N0 < 0 ? 'стержень из сжатого становится растянутым' : 'стержень из растянутого становится сжатым',
            `; скорость v = ${f(r.zero.v)}.`,
          ],
        });
      }
      ex(
        bl,
        'Остановка и отрыв ищутся обходом окружности: v² по интегралу энергии и N по уравнению в проекции на нормаль вычисляются через 0,05°, момент события уточняется делением отрезка пополам.',
      );
      if (ev.kind === 'detach')
        rows.push({ kind: 'main', val: [`отрыв при φ = ${ang(ev.phi)}`], note: `высота ${f(h(ev.phi))} над нижней точкой, v = ${f(ev.v)}` });
      else if (ev.kind === 'stop' && Math.abs(ev.phi - pr.phi0) < 360 - 1e-9)
        rows.push({ kind: 'aux', val: [`остановка при φ = ${f(norm(ev.phi))}°`], note: `высота подъёма ${f(h(ev.phi))} над нижней точкой` });
      else if (ev.kind === 'round') rows.push({ kind: 'aux', val: ['полный оборот'], note: 'без остановки и отрыва' });
      if (r.zero) rows.push({ kind: pr.ask === 'detach' ? 'main' : 'aux', val: [`N = 0 при φ = ${ang(r.zero.phi)}`], note: `v = ${f(r.zero.v)}` });
    }
    steps.push({ title: 'Движение по окружности', blocks: bl });
  }
  // 4. Ответ на вопрос.
  if (pr.ask === 'at' && r.at) {
    const a = r.at;
    const bl: Block[] = [];
    if (!a.reached) bl.push({ k: 'badge', tone: 'bad', text: `точка не доходит до φ₁ = ${f(pr.phi1)}° по окружности` });
    bl.push({
      k: 'eq',
      lines: [
        { c: [`y₁ = R(1 − cos φ₁) = ${f(h(pr.phi1))};  `, v('v'), '₁² = ', f(a.v * a.v), ',  ', b(`v₁ = ${f(a.v)}`)] },
        { c: [v('N'), ' = ', v('m'), v('v'), '₁²/R + mg cos φ₁', sp ? ' − F_пр·n' : '', ' = ', b(`${f(a.N)} ${FU}`)] },
      ],
    });
    bl.push({ k: 'p', c: [cap(meaning(a.N)), '.'] });
    if (a.reached && a.onReturn)
      bl.push({ k: 'p', c: ['Точка проходит это положение на обратном пути (после остановки); скорость по модулю та же — энергия сохраняется.'] });
    steps.push({ title: `В положении φ₁ = ${f(pr.phi1)}°`, blocks: bl });
    if (a.reached) rows.unshift({ kind: 'main', val: [v('v'), sub('1'), ` = ${f(a.v)};  N = ${f(a.N)} ${FU}`], note: meaning(a.N) });
  }
  if (pr.ask === 'full' && r.full) {
    const fu = r.full;
    const bl: Block[] = [];
    if (!fu.possible)
      bl.push({
        k: 'p',
        c: [
          pr.link === 'outer'
            ? 'По внешней поверхности полный оборот невозможен: в нижней части окружности точку уже ничто не прижимает — она сходит со связи.'
            : 'Полный оборот невозможен ни при какой начальной скорости.',
        ],
      });
    else {
      bl.push({ k: 'eq', lines: [{ c: ['наименьшая скорость в положении φ₀ для полного оборота: ', b(`v₀ = ${f(fu.v0min!)}`)] }] });
      if (fu.h != null)
        bl.push({
          k: 'p',
          c: [`Такую скорость точка приобретает, начав движение из покоя на высоте h = y₀ + v₀²/(2g) = ${f(fu.h)} над нижней точкой (${f(fu.h / pr.R)}R).`],
        });
      ex(
        bl,
        pr.link === 'rod'
          ? 'Для двусторонней связи достаточно, чтобы скорость нигде не обращалась в нуль: в верхней точке v ≥ 0.'
          : 'Нить (или прижатие к поверхности) должна удерживать точку всюду: N ≥ 0 и в верхней точке, где mv²/R ≥ mg, т. е. v² ≥ gR.',
      );
      rows.unshift({ kind: 'main', val: [`v₀ ≥ ${f(fu.v0min!)}`], note: fu.h != null ? `полный оборот; с высоты h ≥ ${f(fu.h)}` : 'полный оборот' });
    }
    steps.push({ title: 'Полный оборот', blocks: bl });
  }
  steps.push({ title: 'Ответ', blocks: [{ k: 'answer', rows }] });
  return { steps };
}
