/** Отделы задачника Мещерского по параграфам. */
export function meshPart(par: number): { id: string; title: string } {
  if (par <= 9) return { id: 'statics', title: 'Статика твёрдого тела' };
  if (par <= 25) return { id: 'kinematics', title: 'Кинематика' };
  if (par <= 45) return { id: 'dynamics', title: 'Динамика' };
  return { id: 'analytic', title: 'Аналитическая механика' };
}

