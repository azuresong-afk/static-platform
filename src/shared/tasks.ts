const cap = (s: string) => (s ? s[0].toUpperCase() + s.slice(1) : s);

export function taskInfo(title: string): TaskInfo {
  const mesh = /^Мещерский\s+(\d+)\.(\d+)([^:]*):\s*(.*)$/u.exec(title);
  if (mesh) {
    const par = +mesh[1],
      n = +mesh[2];
    const num = (mesh[1] + '.' + mesh[2] + mesh[3]).trim();
    return {
      book: 'mesh',
      group: 'mesh:' + par,
      groupTitle: `§ ${par}. ${MESH_PARAS[par] ?? ''}`.trim(),
      num,
      label: `${num}: ${mesh[4]}`,
      order: [par, n],
    };
  }
  const ant = /^Антонов,\s*(.*)$/u.exec(title);
  if (ant) {
    const rest = ant[1];
    const task = /^задача\s+(\d+)(?:\.(\d+))?/iu.exec(rest);
    if (task) {
      const t = +task[1];
      return {
        book: 'ant',
        group: 'ant:t' + t,
        groupTitle: `Задача ${t}. ${ANT_TASKS[t] ?? ''}`.trim(),
        num: 'задача ' + task[0].replace(/^задача\s+/iu, ''),
        label: cap(rest),
        order: [12, t, task[2] ? +task[2] : 0],
      };
    }
    const fig = /^рис\.\s*(\d+)\.(\d+)/iu.exec(rest);
    const ch = fig ? +fig[1] : 0;
    return {
      book: 'ant',
      group: 'ant:ch' + ch,
      groupTitle: ch ? `Гл. ${ch}. ${ANT_CHAPTERS[ch] ?? ''}`.trim() : 'Другие задачи пособия',
      num: fig ? `рис. ${fig[1]}.${fig[2]}` : '',
      label: cap(rest),
      order: [ch, fig ? +fig[2] : 0],
    };
  }
  return { book: 'other', group: 'other', groupTitle: 'Другие примеры', num: '', label: title, order: [] };
}

const cmp = (a: number[], b: number[]) => {
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const d = (a[i] ?? -1) - (b[i] ?? -1);
    if (d) return d;
  }
  return 0;
};

export const BOOK_TITLE: Record<Book, string> = { mesh: 'Мещерский', ant: 'Антонов', other: 'Другие примеры' };

export interface TaskGroup<T extends TaskEntry = TaskEntry> {
  group: string;
  book: Book;
  title: string;
  items: (T & { info: TaskInfo })[];
}

/**
 * Группы для списка «Готовая задача»: сначала Мещерский по параграфам, затем Антонов по задачам и главам,
 * затем остальные примеры — в исходном порядке раздела. Внутри групп книги задачи — по номерам.
 */
export function groupTasks<T extends TaskEntry>(items: T[]): TaskGroup<T>[] {
  const withInfo = items.map((it, idx) => ({ ...it, info: taskInfo(it.title), idx }));
  const groups = new Map<string, TaskGroup<T> & { order: number[]; first: number }>();
  for (const it of withInfo) {
    const g = groups.get(it.info.group);
    const { idx, ...rest } = it;
    if (g) g.items.push(rest as T & { info: TaskInfo });
    else
      groups.set(it.info.group, {
        group: it.info.group,
        book: it.info.book,
        title: it.info.groupTitle,
        items: [rest as T & { info: TaskInfo }],
        order: it.info.order.slice(0, it.info.book === 'ant' && it.info.order[0] === 12 ? 2 : 1),
        first: idx,
      });
  }
  const rankBook = (b: Book) => (b === 'mesh' ? 0 : b === 'ant' ? 1 : 2);
  const out = [...groups.values()].sort((a, b) => rankBook(a.book) - rankBook(b.book) || cmp(a.order, b.order) || a.first - b.first);
  for (const g of out) if (g.book !== 'other') g.items.sort((a, b) => cmp(a.info.order, b.info.order));
  return out.map(({ group, book, title, items }) => ({ group, book, title, items }));
}

/** Список задач раздела из записи готовых задач. */
export const taskEntries = (rec: Record<string, { title: string }>): TaskEntry[] => Object.entries(rec).map(([key, v]) => ({ key, title: v.title }));
