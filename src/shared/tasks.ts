/**
 * Источник готовой задачи по её названию: задачник Мещерского (номер, параграф), пособие Антонова (задача или
 * глава) или собственный пример. По этому разбору группируются списки «Готовая задача» в разделах и «Задачник».
 *
 * Названия задач начинаются с источника:
 *   «Мещерский 46.19: …», «Мещерский 48.37–48.38: …», «Мещерский 34.25, 34.27: …»;
 *   «Антонов, задача 4: …», «Антонов, задача 1.1, схема 1 …», «Антонов, рис. 8.5: …».
 * Остальное — примеры приложения.
 */

export type Book = 'mesh' | 'ant' | 'other';

export interface TaskEntry {
  key: string;
  title: string;
}

export interface TaskInfo {
  book: Book;
  /** Группа: «mesh:46», «ant:t4», «ant:ch8», «other». */
  group: string;
  /** Подпись группы: «§ 46. Принцип возможных перемещений», «Задача 4. Тонкостенные сосуды». */
  groupTitle: string;
  /** Номер задачи в книге («46.19», «46.21–46.22», «задача 1.1») или пусто. */
  num: string;
  /** Название без указания книги: «46.19: составная балка…», «Задача 4: рис. 1, строка 1…». */
  label: string;
  /** Ключ сортировки внутри книги. */
  order: number[];
}

